//! PostgreSQL parity, agent T: table-level and named not-null constraints
//! (NO INHERIT, NOT VALID, VALIDATE, DROP, RENAME).
use bicdb_core::{BicDb, DbConfig};
use bicdb_sql::{SqlSession, SqlValue};

fn open(root: &std::path::Path) -> BicDb {
    BicDb::open_with_config(root, DbConfig::default().with_fsync(false)).unwrap()
}

fn rows(session: &mut SqlSession<'_>, sql: &str) -> Vec<String> {
    session
        .execute(sql)
        .unwrap()
        .rows
        .into_iter()
        .map(|row| {
            row.into_iter()
                .map(|value| match value {
                    SqlValue::Null => "NULL".to_string(),
                    SqlValue::Bool(value) => if value { "t" } else { "f" }.to_string(),
                    other => other.to_cell(),
                })
                .collect::<Vec<_>>()
                .join("|")
        })
        .collect()
}

/// Runs each statement on its own, as psql sends them.
fn exec(session: &mut SqlSession<'_>, sql: &str) {
    for statement in sql
        .split(';')
        .filter(|statement| !statement.trim().is_empty())
    {
        if let Err(error) = session.execute(statement) {
            panic!("{statement}: {error:?}");
        }
    }
}

/// The SQLSTATE of the last statement, the earlier ones having succeeded.
fn sqlstate(session: &mut SqlSession<'_>, sql: &str) -> String {
    let statements = sql
        .split(';')
        .filter(|statement| !statement.trim().is_empty())
        .collect::<Vec<_>>();
    let (last, earlier) = statements.split_last().unwrap();
    for statement in earlier {
        exec(session, statement);
    }
    match session.execute(last) {
        Ok(_) => panic!("{last}: succeeded"),
        Err(error) => error.sqlstate().to_string(),
    }
}

const NOT_NULLS: &str = "SELECT conname, convalidated, connoinherit FROM pg_constraint \
     WHERE contype = 'n' AND conrelid = '{t}'::regclass ORDER BY conname";

fn not_nulls(session: &mut SqlSession<'_>, table: &str) -> Vec<String> {
    rows(session, &NOT_NULLS.replace("{t}", table))
}

#[test]
fn table_level_not_null_constraints_name_the_column_constraint() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE TABLE a1 (x int, y int, CONSTRAINT a1_x_named NOT NULL x, NOT NULL y);
             CREATE TABLE a2 (constraint foo not null v, v int generated by default as identity);
             CREATE TABLE a3 (v serial, constraint bar not null v);
             CREATE TABLE a4 (v int CONSTRAINT baz NOT NULL)",
    );
    assert_eq!(
        not_nulls(&mut session, "a1"),
        vec!["a1_x_named|t|f", "a1_y_not_null|t|f"]
    );
    assert_eq!(not_nulls(&mut session, "a2"), vec!["foo|t|f"]);
    assert_eq!(not_nulls(&mut session, "a3"), vec!["bar|t|f"]);
    assert_eq!(not_nulls(&mut session, "a4"), vec!["baz|t|f"]);
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO a1 VALUES (NULL, 1)"),
        "23502"
    );
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO a1 VALUES (1, NULL)"),
        "23502"
    );
    // Conflicting declarations and duplicate names.
    for (sql, state) in [
        (
            "CREATE TABLE f1 (v serial CONSTRAINT p NOT NULL, CONSTRAINT q NOT NULL v)",
            "42601",
        ),
        (
            "CREATE TABLE f2 (v int, CONSTRAINT p NOT NULL v, CONSTRAINT q NOT NULL v)",
            "42601",
        ),
        (
            "CREATE TABLE f3 (v int primary key, NOT NULL v NO INHERIT)",
            "42601",
        ),
        (
            "CREATE TABLE f4 (a int CONSTRAINT dup NOT NULL, b int CONSTRAINT dup NOT NULL)",
            "42710",
        ),
        ("CREATE TABLE f5 (a int, NOT NULL nosuch)", "42703"),
        (
            "CREATE TABLE f6 (a int, NOT NULL a NO INHERIT) PARTITION BY LIST (a)",
            "42P16",
        ),
    ] {
        assert_eq!(sqlstate(&mut session, sql), state, "{sql}");
    }
    assert_eq!(
        rows(
            &mut session,
            "SELECT count(*) FROM pg_class WHERE relname LIKE 'f_'"
        ),
        vec!["0"]
    );
}

#[test]
fn not_null_no_inherit_stays_off_children() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE TABLE p (a int, CONSTRAINT p_nn NOT NULL a NO INHERIT);
             CREATE TABLE c () INHERITS (p);
             INSERT INTO c VALUES (NULL)",
    );
    assert_eq!(not_nulls(&mut session, "p"), vec!["p_nn|t|t"]);
    assert!(not_nulls(&mut session, "c").is_empty());
    // An inheritable one is copied under the parent's name.
    exec(
        &mut session,
        "CREATE TABLE q (a int, CONSTRAINT q_named NOT NULL a);
             CREATE TABLE qc (b int) INHERITS (q)",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT conname, conislocal, coninhcount FROM pg_constraint \
             WHERE contype = 'n' AND conrelid = 'qc'::regclass"
        ),
        vec!["q_named|f|1"]
    );
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO qc VALUES (NULL, 1)"),
        "23502"
    );
}

#[test]
fn alter_table_add_not_null_validates_or_defers() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE TABLE t (a int, b int); INSERT INTO t VALUES (NULL, 1), (300, 3)",
    );
    assert_eq!(
        sqlstate(&mut session, "ALTER TABLE t ADD CONSTRAINT nn NOT NULL a"),
        "23502"
    );
    exec(
        &mut session,
        "ALTER TABLE t ADD CONSTRAINT nn NOT NULL a NOT VALID",
    );
    assert_eq!(not_nulls(&mut session, "t"), vec!["nn|f|f"]);
    // New rows are checked; the old NULL stays and is still found.
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO t VALUES (NULL, 4)"),
        "23502"
    );
    assert_eq!(
        rows(&mut session, "SELECT count(*) FROM t WHERE a IS NULL"),
        vec!["1"]
    );
    assert_eq!(
        rows(&mut session, "SELECT b FROM t ORDER BY a NULLS FIRST"),
        vec!["1", "3"]
    );
    for (sql, state) in [
        (
            "ALTER TABLE t ADD CONSTRAINT nn1 NOT NULL a NOT VALID NO INHERIT",
            "55000",
        ),
        ("ALTER TABLE t ADD CONSTRAINT nn NOT NULL a", "55000"),
        ("ALTER TABLE t ADD PRIMARY KEY (a)", "55000"),
        ("ALTER TABLE t VALIDATE CONSTRAINT nn", "23502"),
        ("ALTER TABLE t ALTER a SET NOT NULL", "23502"),
        ("ALTER TABLE t ADD CONSTRAINT nn NOT NULL b", "42710"),
        ("ALTER TABLE t ADD NOT NULL a, ADD COLUMN c int", "0A000"),
    ] {
        assert_eq!(sqlstate(&mut session, sql), state, "{sql}");
    }
    exec(
        &mut session,
        "UPDATE t SET a = 100 WHERE b = 1; ALTER TABLE t VALIDATE CONSTRAINT nn",
    );
    assert_eq!(not_nulls(&mut session, "t"), vec!["nn|t|f"]);
    // Re-adding the same constraint is a no-op; another name is refused.
    exec(&mut session, "ALTER TABLE t ADD CONSTRAINT nn NOT NULL a");
    assert_eq!(
        sqlstate(
            &mut session,
            "ALTER TABLE t ADD CONSTRAINT other NOT NULL a"
        ),
        "55000"
    );
    exec(
        &mut session,
        "ALTER TABLE t ADD NOT NULL b NOT VALID; ALTER TABLE t RENAME CONSTRAINT nn TO nn2",
    );
    assert_eq!(
        not_nulls(&mut session, "t"),
        vec!["nn2|t|f", "t_b_not_null|f|f"]
    );
    exec(&mut session, "ALTER TABLE t DROP CONSTRAINT nn2; ALTER TABLE t DROP CONSTRAINT t_b_not_null; INSERT INTO t VALUES (NULL, NULL)");
    assert!(not_nulls(&mut session, "t").is_empty());
}

#[test]
fn add_not_null_recurses_to_children_unless_only_or_no_inherit() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE TABLE p (a int); CREATE TABLE c () INHERITS (p);
             INSERT INTO c VALUES (NULL)",
    );
    // The child's NULL fails the inheritable form ...
    assert_eq!(
        sqlstate(&mut session, "ALTER TABLE p ADD CONSTRAINT p_nn NOT NULL a"),
        "23502"
    );
    // ... but not NO INHERIT, which leaves the child alone.
    exec(
        &mut session,
        "ALTER TABLE p ADD CONSTRAINT p_nn NOT NULL a NO INHERIT",
    );
    assert_eq!(not_nulls(&mut session, "p"), vec!["p_nn|t|t"]);
    assert!(not_nulls(&mut session, "c").is_empty());
    exec(
        &mut session,
        "CREATE TABLE p2 (a int); CREATE TABLE c2 () INHERITS (p2);
             INSERT INTO c2 VALUES (NULL);
             ALTER TABLE p2 ADD CONSTRAINT p2_nn NOT NULL a NOT VALID",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT conrelid::regclass::text, conname, convalidated FROM pg_constraint \
             WHERE contype = 'n' AND conrelid IN ('p2'::regclass, 'c2'::regclass) ORDER BY 1"
        ),
        vec!["c2|p2_nn|f", "p2|p2_nn|f"]
    );
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO c2 VALUES (NULL)"),
        "23502"
    );
}

#[test]
fn check_no_inherit_not_valid() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE TABLE k (a int); INSERT INTO k VALUES (-1);
             ALTER TABLE k ADD CONSTRAINT k_c CHECK (a > 0) NO INHERIT NOT VALID",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT conname, convalidated, connoinherit FROM pg_constraint \
             WHERE conrelid = 'k'::regclass"
        ),
        vec!["k_c|f|t"]
    );
    assert_eq!(sqlstate(&mut session, "INSERT INTO k VALUES (-2)"), "23514");
}

#[test]
fn create_schema_with_elements_creates_them_inside_it() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    // The view comes first but runs after the table it reads.
    exec(
        &mut session,
        "CREATE ROLE reader;
             CREATE SCHEMA s1 CREATE VIEW v AS SELECT a FROM t CREATE TABLE t (a int)
               CREATE INDEX t_a ON t (a) CREATE SEQUENCE q GRANT SELECT ON t TO reader",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT relname, relkind FROM pg_class WHERE relnamespace = 's1'::regnamespace ORDER BY 1"
        ),
        vec!["q|S", "t|r", "t_a|i", "v|v"]
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT has_table_privilege('reader', 's1.t', 'SELECT')"
        ),
        vec!["t"]
    );
    assert_eq!(
        rows(&mut session, "SHOW search_path"),
        vec!["\"$user\", public"]
    );
    for (sql, state) in [
        ("CREATE SCHEMA s2 CREATE TABLE other.t (a int)", "42P15"),
        (
            "CREATE SCHEMA IF NOT EXISTS s3 CREATE TABLE t (a int)",
            "0A000",
        ),
        ("CREATE SCHEMA s4 CREATE TEMP TABLE t (a int)", "42P16"),
        // A failing element undoes the whole statement.
        (
            "CREATE SCHEMA s5 CREATE TABLE t (a int) GRANT SELECT ON t TO nosuch_role",
            "42704",
        ),
    ] {
        assert_eq!(sqlstate(&mut session, sql), state, "{sql}");
    }
    assert_eq!(
        rows(
            &mut session,
            "SELECT count(*) FROM pg_namespace WHERE nspname LIKE 's_' AND nspname <> 's1'"
        ),
        vec!["0"]
    );
}

#[test]
fn create_schema_elements_run_as_the_schema_owner() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE ROLE owner_r;
             CREATE SCHEMA AUTHORIZATION owner_r CREATE TABLE t (a int)",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT schemaname, tableowner FROM pg_tables WHERE tablename = 't'"
        ),
        vec!["owner_r|owner_r"]
    );
    // The caller's role is back afterwards.
    assert_eq!(
        rows(&mut session, "SELECT current_user = 'owner_r'"),
        vec!["f"]
    );
}
