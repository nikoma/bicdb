    #[test]
    fn segmented_sync_touches_only_dirty_segment_files() {
        let dir = TempDir::new().unwrap();
        let path = dir.path().join("dirty-segments.pages");
        let store = PageStore::open(
            &path,
            PageStoreOptions::default()
                .with_extent_bytes(MIN_EXTENT_BYTES)
                .with_fsync(true),
        )
        .unwrap();
        let extent_pages = store.extent_pages();
        store.reserve(extent_pages * 4).unwrap();
        store.flush().unwrap();
        let baseline = store.metrics.snapshot();
        assert_eq!(baseline.segments_synced, 4);

        let page_id = extent_pages * 3 + 7;
        let mut page = vec![0_u8; store.page_size() as usize];
        PageHeader::new(page_id, PageType::Heap, store.page_size()).encode(&mut page);
        store.write_page(page_id, &mut page).unwrap();
        store.sync().unwrap();
        let one_dirty_segment = store.metrics.snapshot();
        assert_eq!(
            one_dirty_segment.segments_synced,
            baseline.segments_synced + 1
        );

        store.sync().unwrap();
        assert_eq!(
            store.metrics.snapshot().segments_synced,
            one_dirty_segment.segments_synced,
            "a clean durability barrier must not resync every open segment"
        );
        drop(store);

        let reopened = PageStore::open(
            &path,
            PageStoreOptions::default()
                .with_extent_bytes(MIN_EXTENT_BYTES)
                .with_fsync(true),
        )
        .unwrap();
        let mut read = vec![0_u8; reopened.page_size() as usize];
        let header = reopened.read_page(page_id, &mut read).unwrap();
        assert_eq!(header.page_id, page_id);
        assert_eq!(header.page_type, PageType::Heap);
    }

