//! PostgreSQL parity, agent T: table-level and named not-null constraints
//! (NO INHERIT, NOT VALID, VALIDATE, DROP, RENAME).
use bicdb_core::{BicDb, DbConfig};
use bicdb_sql::{SqlSession, SqlValue};

fn open(root: &std::path::Path) -> BicDb {
    BicDb::open_with_config(root, DbConfig::default().with_fsync(false)).unwrap()
}

fn rows(session: &mut SqlSession<'_>, sql: &str) -> Vec<String> {
    session
        .execute(sql)
        .unwrap()
        .rows
        .into_iter()
        .map(|row| {
            row.into_iter()
                .map(|value| match value {
                    SqlValue::Null => "NULL".to_string(),
                    SqlValue::Bool(value) => if value { "t" } else { "f" }.to_string(),
                    other => other.to_cell(),
                })
                .collect::<Vec<_>>()
                .join("|")
        })
        .collect()
}

/// Runs each statement on its own, as psql sends them.
fn exec(session: &mut SqlSession<'_>, sql: &str) {
    for statement in sql
        .split(';')
        .filter(|statement| !statement.trim().is_empty())
    {
        if let Err(error) = session.execute(statement) {
            panic!("{statement}: {error:?}");
        }
    }
}

/// The SQLSTATE of the last statement, the earlier ones having succeeded.
fn sqlstate(session: &mut SqlSession<'_>, sql: &str) -> String {
    let statements = sql
        .split(';')
        .filter(|statement| !statement.trim().is_empty())
        .collect::<Vec<_>>();
    let (last, earlier) = statements.split_last().unwrap();
    for statement in earlier {
        exec(session, statement);
    }
    match session.execute(last) {
        Ok(_) => panic!("{last}: succeeded"),
        Err(error) => error.sqlstate().to_string(),
    }
}

const NOT_NULLS: &str = "SELECT conname, convalidated, connoinherit FROM pg_constraint \
     WHERE contype = 'n' AND conrelid = '{t}'::regclass ORDER BY conname";

fn not_nulls(session: &mut SqlSession<'_>, table: &str) -> Vec<String> {
    rows(session, &NOT_NULLS.replace("{t}", table))
}

#[test]
fn table_level_not_null_constraints_name_the_column_constraint() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE TABLE a1 (x int, y int, CONSTRAINT a1_x_named NOT NULL x, NOT NULL y);
             CREATE TABLE a2 (constraint foo not null v, v int generated by default as identity);
             CREATE TABLE a3 (v serial, constraint bar not null v);
             CREATE TABLE a4 (v int CONSTRAINT baz NOT NULL)",
    );
    assert_eq!(
        not_nulls(&mut session, "a1"),
        vec!["a1_x_named|t|f", "a1_y_not_null|t|f"]
    );
    assert_eq!(not_nulls(&mut session, "a2"), vec!["foo|t|f"]);
    assert_eq!(not_nulls(&mut session, "a3"), vec!["bar|t|f"]);
    assert_eq!(not_nulls(&mut session, "a4"), vec!["baz|t|f"]);
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO a1 VALUES (NULL, 1)"),
        "23502"
    );
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO a1 VALUES (1, NULL)"),
        "23502"
    );
    // Conflicting declarations and duplicate names.
    for (sql, state) in [
        (
            "CREATE TABLE f1 (v serial CONSTRAINT p NOT NULL, CONSTRAINT q NOT NULL v)",
            "42601",
        ),
        (
            "CREATE TABLE f2 (v int, CONSTRAINT p NOT NULL v, CONSTRAINT q NOT NULL v)",
            "42601",
        ),
        (
            "CREATE TABLE f3 (v int primary key, NOT NULL v NO INHERIT)",
            "42601",
        ),
        (
            "CREATE TABLE f4 (a int CONSTRAINT dup NOT NULL, b int CONSTRAINT dup NOT NULL)",
            "42710",
        ),
        ("CREATE TABLE f5 (a int, NOT NULL nosuch)", "42703"),
        (
            "CREATE TABLE f6 (a int, NOT NULL a NO INHERIT) PARTITION BY LIST (a)",
            "42P16",
        ),
    ] {
        assert_eq!(sqlstate(&mut session, sql), state, "{sql}");
    }
    assert_eq!(
        rows(
            &mut session,
            "SELECT count(*) FROM pg_class WHERE relname LIKE 'f_'"
        ),
        vec!["0"]
    );
}

