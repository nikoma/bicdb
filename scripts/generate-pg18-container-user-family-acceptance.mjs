#!/usr/bin/env node

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const policyPath = join(root, "fixtures/postgresql-18/container-user-family-policy.json");
const policy = JSON.parse(readFileSync(policyPath, "utf8"));
const requiredGates = ["ddl", "dml", "catalog", "dependency", "dump", "restart", "protocol"];
const fixtureIds = loadFixtureIds();

if (policy.target_version !== "18.4" || policy.oracle_image !== "postgres:18.4") {
  throw new Error("container/user-family acceptance must target PostgreSQL 18.4");
}
if (JSON.stringify(policy.gates) !== JSON.stringify(requiredGates)) {
  throw new Error(`gate list must be exactly: ${requiredGates.join(", ")}`);
}
if (!Array.isArray(policy.families) || policy.families.length === 0) {
  throw new Error("at least one container or user-defined family is required");
}

const familyIds = new Set();
let passed = 0;
let notApplicable = 0;
for (const family of policy.families) {
  if (familyIds.has(family.id)) throw new Error(`duplicate family id: ${family.id}`);
  familyIds.add(family.id);
  if (JSON.stringify(Object.keys(family.gates)) !== JSON.stringify(requiredGates)) {
    throw new Error(`${family.id} must define the exact seven gates in policy order`);
  }
  for (const [gateName, gate] of Object.entries(family.gates)) {
    if (!new Set(["pass", "not_applicable"]).has(gate.status)) {
      throw new Error(`${family.id}.${gateName} has invalid status ${gate.status}`);
    }
    if (gate.status === "not_applicable") {
      if (!gate.rationale) throw new Error(`${family.id}.${gateName} requires a rationale`);
      notApplicable += 1;
      continue;
    }
    passed += 1;
    const references = (gate.fixtures?.length || 0) + (gate.sources?.length || 0) + (gate.test ? 1 : 0);
    if (references === 0) throw new Error(`${family.id}.${gateName} has no evidence`);
    for (const fixture of gate.fixtures || []) {
      if (!fixtureIds.has(fixture)) throw new Error(`${family.id}.${gateName} references missing fixture ${fixture}`);
    }
    for (const source of gate.sources || []) assertSource(source, `${family.id}.${gateName}`);
    if (gate.test) {
      const source = assertSource(gate.test.source, `${family.id}.${gateName}`);
      if (!new RegExp(`\\bfn\\s+${escapeRegex(gate.test.name)}\\s*\\(`).test(source)) {
        throw new Error(`${family.id}.${gateName} references missing test ${gate.test.name}`);
      }
    }
  }
}

const total = policy.families.length * requiredGates.length;
const report = {
  schema_version: 1,
  target_version: policy.target_version,
  oracle_image: policy.oracle_image,
  generated_by: "scripts/generate-pg18-container-user-family-acceptance.mjs",
  summary: {
    families: policy.families.length,
    gates_per_family: requiredGates.length,
    applicable_gates_passed: passed,
    not_applicable_gates: notApplicable,
    gates_accounted_for: passed + notApplicable,
    total_gates: total,
  },
  families: policy.families,
};

writeFileSync(
  join(root, "reports/postgresql-18-container-user-family-acceptance.json"),
  `${JSON.stringify(report, null, 2)}\n`,
);
writeFileSync(
  join(root, "docs/postgresql-18-container-user-family-acceptance.md"),
  renderMarkdown(report),
);
console.log(
  `PostgreSQL 18 container/user-family acceptance: ${policy.families.length} families, ${passed}/${total} applicable gates passed, ${notApplicable} not applicable`,
);

function loadFixtureIds() {
  const directories = [
    "fixtures/postgres-compat",
    "fixtures/postgresql-18/type-diff",
  ];
  const ids = new Set();
  for (const directory of directories) {
    for (const name of readdirSync(join(root, directory)).filter((entry) => entry.endsWith(".json"))) {
      const fixture = JSON.parse(readFileSync(join(root, directory, name), "utf8"));
      if (fixture.id) ids.add(fixture.id);
    }
  }
  return ids;
}

function assertSource(relativePath, owner) {
  const path = join(root, relativePath);
  if (!existsSync(path)) throw new Error(`${owner} references missing source ${relativePath}`);
  return readFileSync(path, "utf8");
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function renderMarkdown(report) {
  const headers = requiredGates.map((gate) => `| ${title(gate)} `).join("");
  const divider = requiredGates.map(() => "| :---: ").join("");
  const rows = report.families.map((family) => {
    const cells = requiredGates.map((gate) => family.gates[gate].status === "pass" ? "Pass" : "N/A");
    return `| ${family.label} | ${cells.join(" | ")} |`;
  }).join("\n");
  return `# PostgreSQL 18 Container and User-Family Acceptance\n\n<!-- Generated by scripts/generate-pg18-container-user-family-acceptance.mjs. Do not edit directly. -->\n\nThis is the DT-1602 acceptance matrix for PostgreSQL 18.4 container and user-defined type families. The generator verifies every fixture, source file, and named test referenced by the policy.\n\n## Result\n\n- Families: **${report.summary.families}**\n- Gates accounted for: **${report.summary.gates_accounted_for}/${report.summary.total_gates}**\n- Applicable gates passed: **${report.summary.applicable_gates_passed}**\n- Not-applicable gates with explicit rationales: **${report.summary.not_applicable_gates}**\n\n| Family ${headers}|\n| --- ${divider}|\n${rows}\n\nThe source policy is [\`fixtures/postgresql-18/container-user-family-policy.json\`](../fixtures/postgresql-18/container-user-family-policy.json), and complete machine-readable evidence is in [\`reports/postgresql-18-container-user-family-acceptance.json\`](../reports/postgresql-18-container-user-family-acceptance.json). Regenerate both artifacts with \`node scripts/generate-pg18-container-user-family-acceptance.mjs\`.\n`;
}

function title(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}
