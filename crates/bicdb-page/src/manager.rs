//! Page file management: bounded positioned I/O, allocation, and durability.
//!
//! Phase 1 of `docs/server-paged-storage-todo.md`: "a page manager with bounded
//! `pread`/`pwrite`-style I/O, atomic metadata publication, checksums,
//! torn-page detection, and fault injection."
//!
//! Every read and write is positioned (`read_at`/`write_at`) rather than
//! seek-then-read. That is not only faster — it means the file handle carries no
//! shared cursor, so concurrent readers and writers need no lock between them
//! and a page read is a single syscall.

