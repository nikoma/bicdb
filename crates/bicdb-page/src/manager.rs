/// Exact bounded outcome of one opportunistic tail-reclamation attempt.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TailReclaimReport {
    pub pages_truncated: u64,
    pub tail_pages_scanned: u64,
    pub free_list_pages_scanned: u64,
    pub survivor_links_rewritten: u64,
    pub page_visits: u64,
    pub io_bytes: u64,
    pub deferred: bool,
}

impl TailReclaimReport {
    pub fn validate(self, limits: TailReclaimLimits, page_size: u32) -> Result<()> {
        limits.validate(page_size)?;
        let expected_bytes = self
            .page_visits
            .checked_mul(u64::from(page_size))
            .ok_or_else(|| PageError::InvalidMaintenanceLimits {
                reason: "tail-reclamation report byte accounting overflowed".to_string(),
            })?;
        if self.page_visits > limits.max_page_visits
            || self.io_bytes != expected_bytes
            || self.io_bytes > limits.max_io_bytes
            || self.pages_truncated > self.tail_pages_scanned
            || self.survivor_links_rewritten.saturating_mul(2) > self.page_visits
            || self.deferred && (self.pages_truncated != 0 || self.survivor_links_rewritten != 0)
        {
            return Err(PageError::InvalidMaintenanceLimits {
                reason: "tail-reclamation report is inconsistent with its immutable envelope"
                    .to_string(),
            });
        }
        Ok(())
    }

    fn can_charge(&self, visits: u64, page_size: u32, limits: TailReclaimLimits) -> bool {
        let visits_after = self.page_visits.saturating_add(visits);
        let bytes_after = self
            .io_bytes
            .saturating_add(visits.saturating_mul(u64::from(page_size)));
        visits_after <= limits.max_page_visits && bytes_after <= limits.max_io_bytes
    }

    fn charge(&mut self, visits: u64, page_size: u32) {
        self.page_visits = self.page_visits.saturating_add(visits);
        self.io_bytes = self
            .io_bytes
            .saturating_add(visits.saturating_mul(u64::from(page_size)));
    }
}

/// How the page file should be opened.
#[derive(Clone, Debug)]
pub struct PageStoreOptions {
    /// Bytes per page. Fixed permanently when the file is created; opening an
    /// existing file with a different value is an error rather than a silent
    /// reinterpretation.
    ///
    /// The roadmap requires benchmarking candidate sizes rather than assuming
    /// one. This is the knob that work turns; [`DEFAULT_PAGE_SIZE`] is a
    /// starting point, not a measured conclusion.
    pub page_size: u32,
    /// Whether to `fsync` after metadata publication. Off is for tests and
    /// throughput experiments only — with it off, a crash can lose committed
    /// pages.
    pub fsync: bool,
    /// Create the file if it does not exist.
    pub create: bool,
    /// Bytes per page-file extent when CREATING a new store. `0` keeps the
    /// legacy single-file layout. Non-zero splits the page space into
    /// fixed-size segment files (`store.pages`, `store.pages.1`, …) so
    /// file-level tooling — rsync deltas, parallel uploads, per-file
    /// checksums, multi-volume placement, incremental backup — scales past
    /// hundreds of gigabytes. The value is fixed in the superblock at
    /// creation; opening an existing store uses the stored layout and
    /// ignores this option.
    pub extent_bytes: u64,
}

impl Default for PageStoreOptions {
    fn default() -> Self {
        Self {
            page_size: DEFAULT_PAGE_SIZE,
            fsync: true,
            create: true,
            extent_bytes: 0,
        }
    }
}

impl PageStoreOptions {
    pub fn with_page_size(mut self, page_size: u32) -> Self {
        self.page_size = page_size;
        self
    }

    pub fn with_fsync(mut self, fsync: bool) -> Self {
        self.fsync = fsync;
        self
    }

    pub fn with_extent_bytes(mut self, extent_bytes: u64) -> Self {
        self.extent_bytes = extent_bytes;
        self
    }
}

/// Fault injection points, for the crash-safety matrix Phases 1–3 require.
///
/// Kept in the production type rather than behind `#[cfg(test)]` so integration
/// tests and the eventual crash-matrix harness can drive real code paths. All
/// default to off and cost one relaxed atomic load on the write path.
#[derive(Debug, Default)]
pub struct FaultInjection {
    /// Truncate the Nth write to this many bytes, simulating a torn write.
    /// `(write_index, bytes)`; write indexes count from 1.
    tear_write: Mutex<Option<(u64, usize)>>,
    /// Fail the Nth write with `io::ErrorKind::StorageFull`.
    fail_write: Mutex<Option<u64>>,
    writes: AtomicU64,
}

impl FaultInjection {
    /// Tear write number `nth` after `bytes` bytes.
    pub fn tear_nth_write(&self, nth: u64, bytes: usize) {
        *self.tear_write.lock() = Some((nth, bytes));
    }

    /// Fail write number `nth` as if the disk were full.
    pub fn fail_nth_write(&self, nth: u64) {
        *self.fail_write.lock() = Some(nth);
    }

    pub fn clear(&self) {
        *self.tear_write.lock() = None;
        *self.fail_write.lock() = None;
    }

    pub fn write_count(&self) -> u64 {
        self.writes.load(Ordering::Relaxed)
    }

    /// Returns how many bytes to actually write, or an error to inject.
    fn intercept(&self, len: usize) -> Result<usize> {
        let index = self.writes.fetch_add(1, Ordering::Relaxed) + 1;
        if let Some(nth) = *self.fail_write.lock() {
            if nth == index {
                return Err(PageError::Io {
                    path: PathBuf::from("<fault-injection>"),
                    source: io::Error::new(io::ErrorKind::StorageFull, "injected write failure"),
                });
            }
        }
        if let Some((nth, bytes)) = *self.tear_write.lock() {
            if nth == index {
                return Ok(bytes.min(len));
            }
        }
        Ok(len)
    }
}

/// Fixed, non-configurable latency boundaries. The final snapshot bucket is
/// `+Inf`; these eight bounds therefore produce nine cumulative counters.
pub const PAGE_IO_LATENCY_BUCKET_UPPER_BOUNDS_NANOS: [u64; 8] = [
    1_000,
    10_000,
    100_000,
    1_000_000,
    10_000_000,
    100_000_000,
    1_000_000_000,
    10_000_000_000,
];
pub const PAGE_IO_LATENCY_BUCKET_COUNT: usize = PAGE_IO_LATENCY_BUCKET_UPPER_BOUNDS_NANOS.len() + 1;

/// Process-lifetime latency accumulator with a constant memory and metric
/// footprint. Buckets are stored exclusively and made cumulative in snapshots.
#[derive(Debug)]
pub struct PageIoLatencyMetrics {
    buckets: [AtomicU64; PAGE_IO_LATENCY_BUCKET_COUNT],
    sum_nanos: AtomicU64,
    max_nanos: AtomicU64,
}

impl Default for PageIoLatencyMetrics {
    fn default() -> Self {
        Self {
            buckets: std::array::from_fn(|_| AtomicU64::new(0)),
            sum_nanos: AtomicU64::new(0),
            max_nanos: AtomicU64::new(0),
        }
    }
}

impl PageIoLatencyMetrics {
    fn observe(&self, elapsed: Duration) {
        self.observe_nanos(u64::try_from(elapsed.as_nanos()).unwrap_or(u64::MAX));
    }

    fn observe_nanos(&self, nanos: u64) {
        let bucket = PAGE_IO_LATENCY_BUCKET_UPPER_BOUNDS_NANOS
            .iter()
            .position(|bound| nanos <= *bound)
            .unwrap_or(PAGE_IO_LATENCY_BUCKET_COUNT - 1);
        let _ =
            self.buckets[bucket].fetch_update(Ordering::Relaxed, Ordering::Relaxed, |current| {
                Some(current.saturating_add(1))
            });
        let _ = self
            .sum_nanos
            .fetch_update(Ordering::Relaxed, Ordering::Relaxed, |current| {
                Some(current.saturating_add(nanos))
            });
        self.max_nanos.fetch_max(nanos, Ordering::Relaxed);
    }

    fn snapshot(&self) -> PageIoLatencySnapshot {
        let mut cumulative = [0_u64; PAGE_IO_LATENCY_BUCKET_COUNT];
        let mut running = 0_u64;
        for (index, bucket) in self.buckets.iter().enumerate() {
            running = running.saturating_add(bucket.load(Ordering::Relaxed));
            cumulative[index] = running;
        }
        PageIoLatencySnapshot {
            count: running,
            sum_nanos: self.sum_nanos.load(Ordering::Relaxed),
            max_nanos: self.max_nanos.load(Ordering::Relaxed),
            cumulative_buckets: cumulative,
        }
    }
}

/// Stable fixed-bucket latency evidence. Bucket `i` is the number of operations
/// no slower than bound `i`; the last bucket is the total `+Inf` count.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PageIoLatencySnapshot {
    pub count: u64,
    pub sum_nanos: u64,
    pub max_nanos: u64,
    pub cumulative_buckets: [u64; PAGE_IO_LATENCY_BUCKET_COUNT],
}

impl PageIoLatencySnapshot {
    pub(crate) fn observe(&mut self, elapsed: Duration) {
        self.observe_nanos(u64::try_from(elapsed.as_nanos()).unwrap_or(u64::MAX));
    }

    pub(crate) fn observe_nanos(&mut self, nanos: u64) {
        let bucket = PAGE_IO_LATENCY_BUCKET_UPPER_BOUNDS_NANOS
            .iter()
            .position(|bound| nanos <= *bound)
            .unwrap_or(PAGE_IO_LATENCY_BUCKET_COUNT - 1);
        self.count = self.count.saturating_add(1);
        self.sum_nanos = self.sum_nanos.saturating_add(nanos);
        self.max_nanos = self.max_nanos.max(nanos);
        for cumulative in &mut self.cumulative_buckets[bucket..] {
            *cumulative = cumulative.saturating_add(1);
        }
    }

    /// Validate the representation itself. Individual atomics are sampled
    /// without stopping foreground I/O, so `sum_nanos` and `max_nanos` may be
    /// from an adjacent instant to the bucket counters. The cumulative bucket
    /// sequence is built from one set of exclusive counters and is therefore
    /// always structurally checkable.
    pub fn is_consistent(&self) -> bool {
        let monotonic = self
            .cumulative_buckets
            .windows(2)
            .all(|window| window[0] <= window[1]);
        let terminal = self.cumulative_buckets.last().copied().unwrap_or(0);
        monotonic && terminal == self.count
    }
}

#[derive(Debug, Default)]
struct PageClassIoMetrics {
    reads: AtomicU64,
    writes: AtomicU64,
    bytes_read: AtomicU64,
    bytes_written: AtomicU64,
}

impl PageClassIoMetrics {
    fn record_read(&self, bytes: u64) {
        self.reads.fetch_add(1, Ordering::Relaxed);
        self.bytes_read.fetch_add(bytes, Ordering::Relaxed);
    }

    fn record_write(&self, bytes: u64) {
        self.writes.fetch_add(1, Ordering::Relaxed);
        self.bytes_written.fetch_add(bytes, Ordering::Relaxed);
    }

    fn snapshot(&self) -> PageClassIoSnapshot {
        PageClassIoSnapshot {
            reads: self.reads.load(Ordering::Relaxed),
            writes: self.writes.load(Ordering::Relaxed),
            bytes_read: self.bytes_read.load(Ordering::Relaxed),
            bytes_written: self.bytes_written.load(Ordering::Relaxed),
        }
    }
}

#[derive(Debug, Default)]
struct PageTypeIoMetrics {
    superblock: PageClassIoMetrics,
    heap: PageClassIoMetrics,
    overflow: PageClassIoMetrics,
    btree_interior: PageClassIoMetrics,
    btree_leaf: PageClassIoMetrics,
    free: PageClassIoMetrics,
    unclassified: PageClassIoMetrics,
}

impl PageTypeIoMetrics {
    fn class(&self, page_type: Option<PageType>) -> &PageClassIoMetrics {
        match page_type {
            Some(PageType::Superblock) => &self.superblock,
            Some(PageType::Heap) => &self.heap,
            Some(PageType::Overflow) => &self.overflow,
            Some(PageType::BTreeInterior) => &self.btree_interior,
            Some(PageType::BTreeLeaf) => &self.btree_leaf,
            Some(PageType::Free) => &self.free,
            None => &self.unclassified,
        }
    }

    fn snapshot(&self) -> PageTypeIoSnapshot {
        PageTypeIoSnapshot {
            superblock: self.superblock.snapshot(),
            heap: self.heap.snapshot(),
            overflow: self.overflow.snapshot(),
            btree_interior: self.btree_interior.snapshot(),
            btree_leaf: self.btree_leaf.snapshot(),
            free: self.free.snapshot(),
            unclassified: self.unclassified.snapshot(),
        }
    }
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
