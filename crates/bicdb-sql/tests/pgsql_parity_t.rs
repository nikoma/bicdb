#[test]
fn create_schema_with_elements_creates_them_inside_it() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    // The view comes first but runs after the table it reads.
    exec(
        &mut session,
        "CREATE ROLE reader;
             CREATE SCHEMA s1 CREATE VIEW v AS SELECT a FROM t CREATE TABLE t (a int)
               CREATE INDEX t_a ON t (a) CREATE SEQUENCE q GRANT SELECT ON t TO reader",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT relname, relkind FROM pg_class WHERE relnamespace = 's1'::regnamespace ORDER BY 1"
        ),
        vec!["q|S", "t|r", "t_a|i", "v|v"]
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT has_table_privilege('reader', 's1.t', 'SELECT')"
        ),
        vec!["t"]
    );
    assert_eq!(
        rows(&mut session, "SHOW search_path"),
        vec!["\"$user\", public"]
    );
    for (sql, state) in [
        ("CREATE SCHEMA s2 CREATE TABLE other.t (a int)", "42P15"),
        (
            "CREATE SCHEMA IF NOT EXISTS s3 CREATE TABLE t (a int)",
            "0A000",
        ),
        ("CREATE SCHEMA s4 CREATE TEMP TABLE t (a int)", "42P16"),
        // A failing element undoes the whole statement.
        (
            "CREATE SCHEMA s5 CREATE TABLE t (a int) GRANT SELECT ON t TO nosuch_role",
            "42704",
        ),
    ] {
        assert_eq!(sqlstate(&mut session, sql), state, "{sql}");
    }
    assert_eq!(
        rows(
            &mut session,
            "SELECT count(*) FROM pg_namespace WHERE nspname LIKE 's_' AND nspname <> 's1'"
        ),
        vec!["0"]
    );
}

