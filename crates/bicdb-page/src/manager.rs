        let metrics = PageIoLatencyMetrics::default();
        for nanos in [500, 5_000, 5_000_000_000, 10_000_000_001] {
            metrics.observe_nanos(nanos);
        }

        let snapshot = metrics.snapshot();
        assert_eq!(snapshot.count, 4);
