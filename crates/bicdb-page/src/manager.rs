/// Mutable file-level metadata, published atomically via the superblock.
#[derive(Clone, Copy, Debug, Default)]
struct Superblock {
    page_count: u64,
    free_list_head: PageId,
    free_page_count: u64,
    generation: u64,
    /// Opaque to this crate: the owning engine's root page (e.g. a catalog
    /// B+ tree root). Stored here so "the current root" is published by the same
    /// atomic write that publishes the page count.
    root_page: PageId,
    checkpoint_lsn: u64,
    /// Pages per segment file; `0` = legacy monolithic layout. Non-zero
    /// stores publish the SEGMENTED superblock magic so pre-segmentation
    /// engines fail closed instead of misreading segment 0 as the whole
    /// store.
    extent_pages: u64,
    /// Online-migration target extent size (pages); `0` = none in progress.
    migration_target_pages: u64,
    /// Durable migration progress: pages below this live in segment files.
    migration_watermark: u64,
}

fn free_list_corruption(meta: &Superblock, reason: impl Into<String>) -> PageError {
    PageError::FreeListCorruption {
        head: meta.free_list_head,
        free_pages: meta.free_page_count,
        page_count: meta.page_count,
        reason: reason.into(),
    }
}

/// Validate the constant-time metadata envelope before following or mutating
/// any intrusive free-list link. Full cycle detection belongs to bounded
/// integrity verification; allocation additionally validates the head and its
/// successor so a damaged list fails closed before one page can be handed out
/// twice.
fn validate_free_list_metadata(meta: &Superblock) -> Result<()> {
    if meta.page_count == 0 {
        return Err(free_list_corruption(meta, "page count cannot be zero"));
    }
    if (meta.free_list_head == 0) != (meta.free_page_count == 0) {
        return Err(free_list_corruption(
            meta,
            "head and advertised free-page count disagree",
        ));
    }
    if meta.free_page_count > meta.page_count.saturating_sub(1) {
        return Err(free_list_corruption(
            meta,
            "advertised free pages exceed allocatable pages",
        ));
    }
    if meta.free_list_head >= meta.page_count && meta.free_list_head != 0 {
        return Err(free_list_corruption(
            meta,
            "head points beyond the logical page file",
        ));
    }
    Ok(())
}

/// A first-party page file.
///
/// Concurrency: reads and writes are positioned and need no coordination.
/// Allocation and superblock publication take a single mutex, which is not on
/// the read path.
#[derive(Debug)]
pub struct PageStore {
    path: PathBuf,
    /// Open segment files. Index 0 is `store.pages` (and the whole store in
    /// the legacy monolithic layout); segment `i > 0` is `store.pages.i`.
    /// The vector only ever grows under this lock; positioned I/O on the
    /// contained `File`s needs no coordination.
    segments: parking_lot::RwLock<Vec<File>>,
    /// Segment files changed since the last successful durability barrier.
    /// Held through `sync_data` so a concurrent writer either joins the current
    /// barrier before it starts or remains dirty for the next one.
    dirty_segments: Mutex<BTreeSet<usize>>,
    /// Pages per segment file. `0` = legacy monolithic layout. Atomic
    /// because completing an ONLINE extent migration flips it on a live
    /// store; ordinary opens set it once.
    extent_pages: AtomicU64,
    /// Online-migration target (pages per segment); `0` = none in progress.
    migration_target_pages: AtomicU64,
    /// Pages below this watermark (and >= the target extent size) have been
    /// copied into segment files and are read/written there; pages at or
    /// above it still live at their monolithic offsets. Published durably in
    /// the superblock after every copied batch.
    migration_watermark: AtomicU64,
    /// Serializes un-migrated-zone page writes against migration batch
    /// copies: the copier holds it across copy + atomic watermark publish,
    /// so a write either lands before the copy (and is copied) or after the
    /// publish (and routes to the new location). Touched by writers ONLY
    /// while a migration is active — one atomic load otherwise.
    migration_gate: Mutex<()>,
    page_size: u32,
    fsync: bool,
    meta: Mutex<Superblock>,
    pub metrics: PageIoMetrics,
    pub faults: FaultInjection,
}

impl PageStore {
    /// Open an existing page store using the page size encoded in its
    /// superblock. Intended for verification tooling that must not guess the
    /// database's creation-time page size.
    pub fn open_existing_auto(path: impl AsRef<Path>, fsync: bool) -> Result<Self> {
        let path = path.as_ref();
        let mut options = OpenOptions::new();
        options.read(true);
        #[cfg(unix)]
        options.custom_flags(libc::O_NOFOLLOW);
        let mut file = options.open(path).map_err(|e| PageError::io(path, e))?;
        let metadata = file.metadata().map_err(|e| PageError::io(path, e))?;
        if !metadata.is_file() {
            return Err(PageError::NotAPageFile {
                path: path.to_path_buf(),
                found: [0; 4],
            });
        }
        let mut prefix = [0u8; PAGE_HEADER_BYTES + 12];
        use std::io::Read as _;
        file.read_exact(&mut prefix)
            .map_err(|e| PageError::io(path, e))?;
        let body = &prefix[PAGE_HEADER_BYTES..];
        if body[0..8] != SUPERBLOCK_MAGIC && body[0..8] != SUPERBLOCK_MAGIC_SEGMENTED {
            let mut found = [0u8; 4];
            found.copy_from_slice(&body[0..4]);
            return Err(PageError::NotAPageFile {
                path: path.to_path_buf(),
                found,
            });
        }
        let page_size = u32::from_le_bytes(body[8..12].try_into().unwrap());
        Self::open(
            path,
            PageStoreOptions {
                page_size,
                fsync,
                create: false,
                extent_bytes: 0,
            },
        )
    }

    /// Open or create a page file.
    pub fn open(path: impl AsRef<Path>, options: PageStoreOptions) -> Result<Self> {
        let path = path.as_ref().to_path_buf();
        page::validate_page_size(options.page_size)?;
        validate_extent_bytes(options.extent_bytes, options.page_size)?;

        if let Some(parent) = path.parent() {
            if !parent.as_os_str().is_empty() {
                std::fs::create_dir_all(parent).map_err(|e| PageError::io(parent, e))?;
            }
        }

        let file = OpenOptions::new()
            .read(true)
            .write(true)
            .create(options.create)
            .open(&path)
            .map_err(|e| PageError::io(&path, e))?;

        let len = file.metadata().map_err(|e| PageError::io(&path, e))?.len();

        let store = if len == 0 {
            let store = Self {
                path,
                segments: parking_lot::RwLock::new(vec![file]),
                dirty_segments: Mutex::new(BTreeSet::new()),
                extent_pages: AtomicU64::new(options.extent_bytes / u64::from(options.page_size)),
                migration_target_pages: AtomicU64::new(0),
                migration_watermark: AtomicU64::new(0),
                migration_gate: Mutex::new(()),
                page_size: options.page_size,
                fsync: options.fsync,
                meta: Mutex::new(Superblock {
                    page_count: 1, // the superblock itself
                    ..Default::default()
                }),
                metrics: PageIoMetrics::default(),
                faults: FaultInjection::default(),
            };
            store.write_superblock()?;
            store
        } else {
            let mut store = Self {
                path,
                segments: parking_lot::RwLock::new(vec![file]),
                dirty_segments: Mutex::new(BTreeSet::new()),
                // The stored layout is authoritative for existing stores;
                // learned from the superblock below.
                extent_pages: AtomicU64::new(0),
                migration_target_pages: AtomicU64::new(0),
                migration_watermark: AtomicU64::new(0),
                migration_gate: Mutex::new(()),
                page_size: options.page_size,
                fsync: options.fsync,
                meta: Mutex::new(Superblock::default()),
                metrics: PageIoMetrics::default(),
                faults: FaultInjection::default(),
            };
            let superblock = store.read_superblock(options.page_size)?;
            store
                .extent_pages
                .store(superblock.extent_pages, Ordering::Release);
            store
                .migration_target_pages
                .store(superblock.migration_target_pages, Ordering::Release);
            store
                .migration_watermark
                .store(superblock.migration_watermark, Ordering::Release);
            *store.meta.lock() = superblock;
            store.page_size = options.page_size;
            store.open_existing_segments(superblock.page_count)?;
            store
        };

        Ok(store)
    }

    /// Path of segment `index`: the base path for 0, `<base>.<index>` above.
    fn segment_path(&self, index: usize) -> PathBuf {
        segment_path_for(&self.path, index)
    }

    /// Open every segment the published page count requires (plus any
    /// trailing segment a crash left behind after a write but before the
    /// superblock publish — those pages are logically absent and the next
    /// tail reclamation removes them). A REQUIRED segment that is missing is
    /// store corruption and fails closed.
    fn open_existing_segments(&mut self, page_count: u64) -> Result<()> {
        let extent_pages = match (
            self.extent_pages(),
            self.migration_target_pages.load(Ordering::Acquire),
        ) {
            (0, 0) => return Ok(()),
            (0, target) => target, // mid-migration: watermark pages live in segments
            (extent, _) => extent,
        };
        let required = page_count.div_ceil(extent_pages).max(1) as usize;
        let mut segments = self.segments.write();
        let mut index = segments.len();
        loop {
            let path = self.segment_path(index);
            match OpenOptions::new().read(true).write(true).open(&path) {
                Ok(file) => {
                    segments.push(file);
                    index += 1;
                }
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => break,
                Err(error) => return Err(PageError::io(&path, error)),
            }
        }
        if segments.len() < required {
            return Err(PageError::SegmentMissing {
                path: segment_path_for(&self.path, segments.len()),
                page_count,
            });
        }
        Ok(())
    }

    /// `page_id` → (segment index, byte offset within that segment).
    ///
    /// During an online migration, pages below the durable watermark route
    /// to their new segment locations and everything else stays at its
    /// monolithic offset. Pages inside the first extent have the SAME
    /// offset in both layouts (segment 0 is the base file), which is what
    /// lets the migration begin without moving a byte.
    fn locate(&self, page_id: PageId) -> (usize, u64) {
        let extent_pages = self.extent_pages.load(Ordering::Acquire);
        if extent_pages > 0 {
            return (
                (page_id / extent_pages) as usize,
                (page_id % extent_pages) * u64::from(self.page_size),
            );
        }
        let target = self.migration_target_pages.load(Ordering::Acquire);
        if target > 0 && page_id < self.migration_watermark.load(Ordering::Acquire) {
            return (
                (page_id / target) as usize,
                (page_id % target) * u64::from(self.page_size),
            );
        }
        (0, page::file_offset(page_id, self.page_size))
    }

    /// Create segment files up through `index` (write path only — reads of a
    /// missing segment are out-of-bounds by construction).
    fn ensure_segment(&self, index: usize) -> Result<()> {
        if index < self.segments.read().len() {
            return Ok(());
        }
        let mut segments = self.segments.write();
        while segments.len() <= index {
            let path = self.segment_path(segments.len());
            let file = OpenOptions::new()
                .read(true)
                .write(true)
                .create(true)
                .open(&path)
                .map_err(|e| PageError::io(&path, e))?;
            segments.push(file);
        }
        Ok(())
    }

    fn mark_segment_dirty(&self, index: usize) {
        self.dirty_segments.lock().insert(index);
    }

    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Pages per segment file; `0` for the legacy monolithic layout (or a
    /// store whose online migration has not completed yet).
    pub fn extent_pages(&self) -> u64 {
        self.extent_pages.load(Ordering::Acquire)
    }

    /// Online migration status: `Some((target_extent_pages, watermark))`
    /// while one is in progress.
    pub fn extent_migration_status(&self) -> Option<(u64, u64)> {
        let target = self.migration_target_pages.load(Ordering::Acquire);
        (target > 0).then(|| (target, self.migration_watermark.load(Ordering::Acquire)))
    }

    /// Paths of every current segment file, ascending. Segment 0 is the base
    /// path; a monolithic store reports exactly one entry.
    pub fn segment_paths(&self) -> Vec<PathBuf> {
        (0..self.segments.read().len())
            .map(|index| self.segment_path(index))
            .collect()
    }

    pub fn page_size(&self) -> u32 {
        self.page_size
    }

    /// Current total byte length of the mutable page file(s).
    ///
    /// This is intentionally read from the open file descriptors rather than
    /// derived from `page_count`: after a crash between publishing a shorter
    /// superblock and truncating the file, the durable logical length may be
    /// smaller than the still-present physical tail. Exposing both figures is
    /// what lets operators detect and safely schedule another reclamation pass.
    pub fn file_size_bytes(&self) -> Result<u64> {
        let segments = self.segments.read();
        let mut total = 0u64;
        for (index, file) in segments.iter().enumerate() {
            total = total.saturating_add(
                file.metadata()
                    .map(|metadata| metadata.len())
                    .map_err(|error| PageError::io(self.segment_path(index), error))?,
            );
        }
        Ok(total)
    }

    pub fn page_count(&self) -> u64 {
        self.meta.lock().page_count
    }

    pub fn free_page_count(&self) -> u64 {
        self.meta.lock().free_page_count
    }

    pub fn free_list_head(&self) -> PageId {
        self.meta.lock().free_list_head
    }

    /// Detach allocator state before WAL page replay.
    ///
    /// WAL contains page after-images but not the superblock's intrusive
    /// free-list head. Replaying an allocated image over a page still reachable
    /// from that list would make a live page reusable. Detaching the list first
    /// makes recovery safe in constant time: former free pages become orphaned
    /// reusable space and can be recovered later by the bounded, resumable
    /// orphan scanner. A crash after this publication leaks space but can never
    /// expose a live page through the allocator.
    pub(crate) fn detach_free_list_for_recovery(&self) -> Result<u64> {
        let detached = {
            let mut meta = self.meta.lock();
            validate_free_list_metadata(&meta)?;
            let detached = meta.free_page_count;
            if meta.free_list_head == 0 && detached == 0 {
                return Ok(0);
            }
            meta.free_list_head = 0;
            meta.free_page_count = 0;
            meta.generation = meta.generation.saturating_add(1);
            self.write_superblock_meta(&meta)?;
            detached
        };
        self.sync()?;
        Ok(detached)
    }

    pub fn root_page(&self) -> PageId {
        self.meta.lock().root_page
    }

    pub fn checkpoint_lsn(&self) -> u64 {
        self.meta.lock().checkpoint_lsn
    }

    /// Publish a new root page and checkpoint LSN atomically.
    ///
    /// "Atomic metadata publication" in the roadmap means exactly this: the
    /// superblock is one page, written with one `pwrite` and guarded by its own
    /// checksum and trailer, so a crash leaves either the old root or the new
    /// one — never a mixture, and never a root pointing at a half-built tree.
    pub fn publish_root(&self, root_page: PageId, checkpoint_lsn: u64) -> Result<()> {
        {
            let mut meta = self.meta.lock();
            meta.root_page = root_page;
            meta.checkpoint_lsn = checkpoint_lsn;
            meta.generation = meta.generation.saturating_add(1);
        }
        self.write_superblock()?;
        self.sync()
    }

    /// Allocate a page, reusing a freed one when available.
    ///
    /// Reuse takes from the head of an intrusive free list threaded through the
    /// `next_page` header field, so the free list costs no separate structure
    /// and survives restart without a rebuild.
    pub fn allocate(&self, page_type: PageType) -> Result<PageId> {
        if matches!(page_type, PageType::Superblock | PageType::Free) {
            return Err(PageError::InvalidAllocationPageType {
                page_type: page_type as u8,
            });
        }
        let mut meta = self.meta.lock();
        validate_free_list_metadata(&meta)?;
        let (page_id, page_generation_floor) = if meta.free_list_head != 0 {
            let head = meta.free_list_head;
            let header = self.read_header(head)?;
            if header.page_type != PageType::Free {
                return Err(PageError::UnexpectedPageType {
                    page_id: head,
                    found: header.page_type as u8,
                    expected: PageType::Free as u8,
                });
            }
            let next = header.next_page;
            if next == head || (next != 0 && next >= meta.page_count) {
                return Err(free_list_corruption(
                    &meta,
                    format!("free page {head} links to invalid next page {next}"),
                ));
            }
            if (meta.free_page_count == 1) != (next == 0) {
                return Err(free_list_corruption(
                    &meta,
                    format!(
                        "head page {head} links to {next}, inconsistent with the advertised count"
                    ),
                ));
            }
            if next != 0 {
                let next_header = self.read_header(next)?;
                if next_header.page_type != PageType::Free {
                    return Err(PageError::UnexpectedPageType {
                        page_id: next,
                        found: next_header.page_type as u8,
                        expected: PageType::Free as u8,
                    });
                }
                if next_header.next_page == head {
                    return Err(free_list_corruption(
                        &meta,
                        format!("free pages {head} and {next} form a cycle"),
                    ));
                }
            }
            meta.free_list_head = next;
            meta.free_page_count -= 1;
            (head, header.generation)
        } else {
            let id = meta.page_count;
            // During an online extent migration the copier reads the logical
            // allocation horizon from `page_count` and then copies every page
            // below it from the monolith.  Publishing the increment before a
            // positioned write had extended the file let the copier observe a
            // page that had no backing bytes yet, producing a legitimate
            // short read under a concurrent allocator.  Establish the sparse
            // backing first; the subsequent page write is serialized with the
            // migration gate and therefore lands on whichever side of the
            // watermark becomes authoritative.
            if self.migration_target_pages.load(Ordering::Acquire) != 0 {
                self.extend_to(id.saturating_add(1))?;
            }
            meta.page_count += 1;
            (id, 0)
        };
        meta.generation = meta.generation.max(page_generation_floor).saturating_add(1);
        let generation = meta.generation;
        drop(meta);

        // A freshly allocated page is written out zeroed with its new type, so
        // that a reader can never observe a stale predecessor's contents through
        // a reused id — the roadmap's "cannot expose stale tuple data after slot
        // reuse" requirement, applied at page granularity.
        let mut page = vec![0u8; self.page_size as usize];
        PageHeader::new(page_id, page_type, self.page_size).encode(&mut page);
        self.write_page_raw(page_id, &mut page, generation)?;

        self.metrics.allocations.fetch_add(1, Ordering::Relaxed);
        Ok(page_id)
    }

    /// Grow the file to at least `page_count` pages without writing them.
    ///
    /// The extension is sparse: the filesystem allocates blocks only when pages
    /// are actually written, so reserving a large id range costs no physical
    /// disk. This is how extent-style growth avoids a write-amplifying
    /// pre-fill, and it is what makes the >4 GiB / >1 TiB offset tests runnable
    /// in CI (see `tests/large_offsets.rs`).
    pub fn reserve(&self, page_count: u64) -> Result<()> {
        let mut meta = self.meta.lock();
        if page_count <= meta.page_count {
            return Ok(());
        }
        self.extend_to(page_count)?;
        meta.page_count = page_count;
        meta.generation += 1;
        Ok(())
    }

    /// Sparse-extend the file layout so every page below `page_count` has
    /// backing bytes. Monolithic: one `set_len`. Segmented: full-size
    /// intermediate segments plus a partial last one; grow-only, since a
    /// crash-leftover longer tail is reclaimed by checkpoint truncation, not
    /// here.
    fn extend_to(&self, page_count: u64) -> Result<()> {
        let extent_pages = self.extent_pages();
        if extent_pages == 0 {
            // Monolithic — including mid-migration, where the un-migrated
            // tail (and all new growth) lives at monolithic offsets.
            let bytes = page_count
                .checked_mul(u64::from(self.page_size))
                .ok_or(PageError::InvalidPageSize(self.page_size))?;
            let segments = self.segments.read();
            segments[0]
                .set_len(bytes)
                .map_err(|e| PageError::io(&self.path, e))?;
            drop(segments);
            self.mark_segment_dirty(0);
            return Ok(());
        }
        let last_segment = ((page_count - 1) / extent_pages) as usize;
        self.ensure_segment(last_segment)?;
        let segments = self.segments.read();
        let extent_bytes = extent_pages * u64::from(self.page_size);
        let mut changed = Vec::new();
        for (index, file) in segments.iter().enumerate().take(last_segment + 1) {
            let target = if index < last_segment {
                extent_bytes
            } else {
                (page_count - index as u64 * extent_pages) * u64::from(self.page_size)
            };
            let current = file
                .metadata()
                .map_err(|e| PageError::io(self.segment_path(index), e))?
                .len();
            if current < target {
                file.set_len(target)
                    .map_err(|e| PageError::io(self.segment_path(index), e))?;
                changed.push(index);
            }
        }
        drop(segments);
        self.dirty_segments.lock().extend(changed);
        Ok(())
    }

    /// Return a page to the free list.
    pub fn free(&self, page_id: PageId) -> Result<()> {
        if page_id == SUPERBLOCK_PAGE_ID {
            return Err(PageError::UnexpectedPageType {
                page_id,
                found: PageType::Superblock as u8,
                expected: PageType::Free as u8,
            });
        }
        let mut meta = self.meta.lock();
        validate_free_list_metadata(&meta)?;
        if page_id >= meta.page_count {
            return Err(PageError::OutOfBounds {
                page_id,
                page_count: meta.page_count,
            });
        }
        if page_id == meta.root_page {
            return Err(PageError::CannotFreeRootPage { page_id });
        }
        let existing = self.read_header(page_id)?;
        if existing.page_type == PageType::Free {
            return Err(PageError::PageAlreadyFree { page_id });
        }
        if existing.page_type == PageType::Superblock {
            return Err(PageError::UnexpectedPageType {
                page_id,
                found: existing.page_type as u8,
                expected: PageType::Free as u8,
            });
        }
        let previous_head = meta.free_list_head;
        meta.free_list_head = page_id;
        meta.free_page_count += 1;
        meta.generation = meta.generation.max(existing.generation).saturating_add(1);
        let generation = meta.generation;

        let mut page = vec![0u8; self.page_size as usize];
        let mut header = PageHeader::new(page_id, PageType::Free, self.page_size);
        header.next_page = previous_head;
        header.encode(&mut page);
        self.write_page_raw(page_id, &mut page, generation)?;
        drop(meta);

        self.metrics.frees.fetch_add(1, Ordering::Relaxed);
        Ok(())
    }

    /// Adopt an already-materialized free-list segment.
    ///
    /// Unlike [`Self::free`], the pages' Free images (with their `next_page`
    /// links, the LAST of which points at the current list head) were written
    /// through the buffer pool and WAL by the caller — this only publishes
    /// the new head and count in the superblock. The caller must have made
    /// the images durable first: the superblock is the atomic commit point,
    /// and a crash before it leaves the pages typed Free but unlisted, which
    /// leaks them (consistent) rather than corrupting the list.
    pub fn adopt_free_pages(&self, new_head: PageId, count: u64) -> Result<()> {
        if count > MAX_FREE_LIST_ADOPTION_PAGES {
            return Err(PageError::InvalidMaintenanceLimits {
                reason: format!(
                    "cannot atomically adopt more than {MAX_FREE_LIST_ADOPTION_PAGES} free pages"
                ),
            });
        }
        {
            let mut meta = self.meta.lock();
            validate_free_list_metadata(&meta)?;
            if count == 0 {
                if new_head == 0 {
                    return Ok(());
                }
                return Err(free_list_corruption(
                    &meta,
                    "a zero-length free segment has a nonzero head",
                ));
            }
            if new_head == 0 || new_head >= meta.page_count {
                return Err(free_list_corruption(
                    &meta,
                    "adopted free-segment head is outside the logical page file",
                ));
            }
            let new_total = meta
                .free_page_count
                .checked_add(count)
                .filter(|total| *total <= meta.page_count.saturating_sub(1))
                .ok_or_else(|| {
                    free_list_corruption(
                        &meta,
                        "adopted segment would exceed the allocatable page count",
                    )
                })?;

            // The segment is bounded by the originating vacuum step. Validate
            // its exact length and tail binding without walking the pre-existing
            // free list or allocating a membership set.
            let old_head = meta.free_list_head;
            let mut cursor = new_head;
            for index in 0..count {
                if cursor == 0 || cursor >= meta.page_count {
                    return Err(free_list_corruption(
                        &meta,
                        format!("adopted segment ends early at position {index}"),
                    ));
                }
                let header = self.read_header(cursor)?;
                if header.page_type != PageType::Free {
                    return Err(PageError::UnexpectedPageType {
                        page_id: cursor,
                        found: header.page_type as u8,
                        expected: PageType::Free as u8,
                    });
                }
                let last = index + 1 == count;
                if last {
                    if header.next_page != old_head {
                        return Err(free_list_corruption(
                            &meta,
                            format!(
                                "adopted segment tail {cursor} does not bind to old head {old_head}"
                            ),
                        ));
                    }
                } else if header.next_page == 0 || header.next_page == old_head {
                    return Err(free_list_corruption(
                        &meta,
                        format!("adopted segment ends before its declared {count} pages"),
                    ));
                }
                cursor = header.next_page;
            }
            meta.free_list_head = new_head;
            meta.free_page_count = new_total;
            meta.generation += 1;
        }
        self.metrics.frees.fetch_add(count, Ordering::Relaxed);
        self.write_superblock()?;
        self.sync()
    }

    /// Walk the free list and truncate it at the first corrupt link,
    /// keeping the provably-valid prefix.
    ///
    /// The failure this repairs: a crash mid-mutation (observed after an
    /// OOM-kill during a bulk import) leaves the intrusive list REACHABLE but
    /// pointing at a page that is no longer typed Free — every subsequent
    /// allocation then fails closed with `UnexpectedPageType`, making the
    /// whole store read-only. [`Self::abandon_detached_free_page_count`]
    /// deliberately refuses this state (its contract is `head == 0`).
    ///
    /// The walk validates each link exactly as `allocate` would: in bounds,
    /// typed Free, acyclic, and never longer than the advertised count. The
    /// first violation ends the valid prefix; everything from the violating
    /// page onward is abandoned (LEAKED, never guessed at — a page of unknown
    /// provenance must not re-enter circulation). With `apply` the truncation
    /// is published: the last valid page's `next_page` is rewritten to 0 (or
    /// the head zeroed when nothing survives), the count set to the prefix
    /// length, and the superblock committed. A dry run only reports.
    ///
    /// The caller must hold exclusive ownership of the database directory.
    pub fn truncate_free_list_at_corruption(&self, apply: bool) -> Result<FreeListTruncateReport> {
        let mut meta = self.meta.lock();
        let advertised = meta.free_page_count;
        let page_count = meta.page_count;
        let mut chain: Vec<(PageId, PageId)> = Vec::new();
        let mut cursor = meta.free_list_head;
        let mut corrupt_page = None;
        let mut corrupt_reason = None;
        while cursor != 0 {
            if chain.len() as u64 >= advertised {
                corrupt_page = Some(cursor);
                corrupt_reason = Some(format!(
                    "walk exceeds the advertised {advertised} pages (cycle?)"
                ));
                break;
            }
            if cursor >= page_count {
                corrupt_page = Some(cursor);
                corrupt_reason = Some(format!(
                    "link points beyond the logical file ({cursor} >= {page_count})"
                ));
                break;
            }
            let header = match self.read_header(cursor) {
                Ok(header) => header,
                Err(error) => {
                    corrupt_page = Some(cursor);
                    corrupt_reason = Some(format!("header unreadable: {error}"));
                    break;
                }
            };
            if header.page_type != PageType::Free {
                corrupt_page = Some(cursor);
                corrupt_reason = Some(format!(
                    "page has type {}, expected {}",
                    header.page_type as u8,
                    PageType::Free as u8
                ));
                break;
            }
            if chain.iter().any(|(page, _)| *page == header.next_page) {
                chain.push((cursor, header.next_page));
                corrupt_page = Some(header.next_page);
                corrupt_reason = Some("links form a cycle".to_string());
                // The cycling link itself is invalid: drop the page that
                // carries it from the valid prefix so the truncation point
                // is the page BEFORE the repeated target.
                chain.pop();
                break;
            }
            chain.push((cursor, header.next_page));
            cursor = header.next_page;
        }
        let valid_prefix = chain.len() as u64;
        let needs_repair = corrupt_page.is_some() || valid_prefix != advertised;
        let mut report = FreeListTruncateReport {
            advertised,
            valid_prefix,
            corrupt_page,
            corrupt_reason,
            applied: false,
        };
        if !apply || !needs_repair {
            return Ok(report);
        }
        // Publish the truncation. Page write first, superblock second: a
        // crash between them leaves a shorter-than-advertised list, which the
        // walk above already classifies as repairable — never a corrupt one.
        if let Some(&(last_valid, last_next)) = chain.last() {
            if last_next != 0 {
                let mut page = vec![0u8; self.page_size as usize];
                let mut header = PageHeader::new(last_valid, PageType::Free, self.page_size);
                header.next_page = 0;
                header.encode(&mut page);
                self.write_page_raw(last_valid, &mut page, meta.generation)?;
            }
            meta.free_page_count = valid_prefix;
        } else {
            meta.free_list_head = 0;
            meta.free_page_count = 0;
        }
        meta.generation = meta.generation.saturating_add(1);
        self.write_superblock_meta(&meta)?;
        drop(meta);
        self.sync()?;
        report.applied = true;
        Ok(report)
    }

    /// Abandon a stale free-page count whose intrusive-list head was already
    /// durably detached by an interrupted older checkpoint implementation.
    ///
    /// This deliberately leaks the advertised pages instead of guessing which
    /// physical pages were reusable. It is therefore safe only for the exact
    /// fail-closed state `head == 0 && free_page_count == expected_count` and
    /// requires an operator-supplied count as a fencing token. The caller must
    /// hold exclusive ownership of the database directory.
    pub fn abandon_detached_free_page_count(&self, expected_count: u64) -> Result<u64> {
        let abandoned = {
            let mut meta = self.meta.lock();
            if meta.free_list_head != 0 {
                return Err(free_list_corruption(
                    &meta,
                    "repair refuses to abandon a reachable free list",
                ));
            }
            if meta.free_page_count == 0 || meta.free_page_count != expected_count {
                return Err(PageError::InvalidMaintenanceLimits {
                    reason: format!(
                        "expected detached free-page count {expected_count}, found {}",
                        meta.free_page_count
                    ),
                });
            }
            let abandoned = meta.free_page_count;
            meta.free_page_count = 0;
            meta.generation = meta.generation.saturating_add(1);
            self.write_superblock_meta(&meta)?;
            abandoned
        };
        self.sync()?;
        Ok(abandoned)
    }

    /// Walk the intrusive free list and return its member page ids, ascending.
    ///
    /// Returns `Ok(None)` when the walk would visit more than `max_visits`
    /// pages, letting a bounded caller defer rather than allocate an unbounded
    /// membership set. A non-Free member is free-list corruption and fails the
    /// walk. A cycle is not separately detected: it revisits pages until the
    /// `max_visits` budget is exhausted and the walk defers with `Ok(None)`,
    /// so a cyclic list surfaces as "too large" rather than spinning forever.
    pub fn free_list_members(&self, max_visits: u64) -> Result<Option<Vec<PageId>>> {
        let mut members: Vec<PageId> = Vec::new();
        let mut cursor = self.meta.lock().free_list_head;
        while cursor != 0 {
            if members.len() as u64 >= max_visits {
                return Ok(None);
            }
            let header = self.read_header(cursor)?;
            if header.page_type != PageType::Free {
                return Err(free_list_corruption(
                    &self.meta.lock(),
                    format!("free list member {cursor} is not typed Free"),
                ));
            }
            members.push(cursor);
            cursor = header.next_page;
            // A cycle is bounded by `max_visits`: it revisits pages until the
            // budget is exhausted and the walk defers rather than spinning.
        }
        members.sort_unstable();
        Ok(Some(members))
    }

    /// Truncate the file's trailing run of FREE pages.
    ///
    /// Finds the largest physical suffix `[K, page_count)` containing only
    /// Free pages, validates the bounded intrusive list, detaches that list
    /// atomically, rewrites surviving links, publishes the shorter logical
    /// file, and only then truncates physical bytes. Every mutation window is
    /// leak-consistent: an interruption after detachment loses reusable-space
    /// knowledge but leaves valid allocation authority, while publication
    /// before `set_len` merely leaves ignored tail bytes for the next pass.
    ///
    /// The caller must guarantee no locator to `[K, page_count)` can be
    /// dereferenced concurrently and that the WAL holds no image of those
    /// pages (i.e. run at a checkpoint that truncated the log) — otherwise
    /// recovery would re-extend the file.
    pub fn truncate_trailing_free_pages(&self) -> Result<u64> {
        Ok(self
            .truncate_trailing_free_pages_bounded(TailReclaimLimits::default())?
            .pages_truncated)
    }

    /// Returns interior free-page bytes to the filesystem by punching holes
    /// in each free page beyond its first filesystem block. The page header
    /// (type + free-list link) lives in that first block and stays
    /// allocated, so chain walks keep working; the punched remainder reads
    /// as zeros, which is safe because allocation always writes a full page
    /// image before first use. Holds the free-list meta lock across the
    /// walk so no punched page can be concurrently allocated mid-punch.
    ///
    /// Purely advisory space return: a crash at any byte loses nothing
    /// (zeros for zeros), and re-punching an already-sparse page is a
    /// harmless metadata no-op. Unsupported platforms/filesystems report
    /// `supported: false` and punch nothing.
    pub fn punch_free_pages_bounded(&self, max_pages: u64) -> Result<HolePunchReport> {
        const KEEP_BYTES: u64 = 4_096;
        let mut report = HolePunchReport {
            supported: cfg!(target_os = "linux"),
            ..HolePunchReport::default()
        };
        let page_size = u64::from(self.page_size);
        if page_size <= KEEP_BYTES.saturating_mul(2) || max_pages == 0 {
            report.supported = report.supported && page_size > KEEP_BYTES.saturating_mul(2);
            return Ok(report);
        }
        #[cfg(not(target_os = "linux"))]
        {
            return Ok(report);
        }
        #[cfg(target_os = "linux")]
        {
            use std::os::unix::io::AsRawFd;
            let meta = self.meta.lock();
            validate_free_list_metadata(&meta)?;
            let mut cursor = meta.free_list_head;
            let mut visited: u64 = 0;
            while cursor != 0 && report.pages_punched < max_pages {
                visited += 1;
                if visited > meta.free_page_count {
                    return Err(free_list_corruption(
                        &meta,
                        "free-list traversal exceeds its advertised count",
                    ));
                }
                let header = self.read_header(cursor)?;
                if header.page_type != PageType::Free {
                    return Err(PageError::UnexpectedPageType {
                        page_id: cursor,
                        found: header.page_type as u8,
                        expected: PageType::Free as u8,
                    });
                }
                // Canonicalize to the same header+zeros image `free()`
                // writes, so the stored checksum covers exactly what the
                // punched page will read back. Vacuum-adopted free pages
                // may still carry their old row bytes under the checksum.
                // Keep both the first and last filesystem blocks: the header
                // and checksum trailer retain a monotonic per-page generation,
                // while the zero middle can still be returned to the filesystem.
                let mut image = vec![0u8; self.page_size as usize];
                let mut fresh = PageHeader::new(cursor, PageType::Free, self.page_size);
                fresh.next_page = header.next_page;
                fresh.encode(&mut image);
                self.write_page_raw(cursor, &mut image, header.generation.saturating_add(1))?;

                let (segment_index, offset) = self.locate(cursor);
                let segments = self.segments.read();
                let Some(file) = segments.get(segment_index) else {
                    return Err(free_list_corruption(
                        &meta,
                        format!("free page {cursor} maps to missing segment {segment_index}"),
                    ));
                };
                let punch_offset = offset + KEEP_BYTES;
                let punch_len = page_size - KEEP_BYTES.saturating_mul(2);
                let result = unsafe {
                    libc::fallocate(
                        file.as_raw_fd(),
                        libc::FALLOC_FL_PUNCH_HOLE | libc::FALLOC_FL_KEEP_SIZE,
                        punch_offset as libc::off_t,
                        punch_len as libc::off_t,
                    )
                };
                if result != 0 {
                    let errno = std::io::Error::last_os_error();
                    if matches!(
                        errno.raw_os_error(),
                        Some(libc::EOPNOTSUPP) | Some(libc::ENOSYS) | Some(libc::EINVAL)
                    ) {
                        // Filesystem without punch support: report and stop.
                        report.supported = false;
                        return Ok(report);
                    }
                    return Err(PageError::Io {
                        path: self.path.clone(),
                        source: errno,
                    });
                }
                drop(segments);
                report.pages_punched += 1;
                report.bytes_punched += punch_len;
                cursor = header.next_page;
            }
            self.metrics
                .hole_punch_pages
                .fetch_add(report.pages_punched, Ordering::Relaxed);
            self.metrics
                .hole_punch_bytes
                .fetch_add(report.bytes_punched, Ordering::Relaxed);
            Ok(report)
        }
    }

    /// Bounded checkpoint tail reclamation. Preflight is read-only; an
    /// operation that cannot fit its exact page and I/O envelope is deferred
    /// without mutation. Once mutation starts, the superblock first detaches
    /// the old list. A crash may leak reusable pages but cannot make one page
    /// allocatable twice.
    pub fn truncate_trailing_free_pages_bounded(
        &self,
        limits: TailReclaimLimits,
    ) -> Result<TailReclaimReport> {
        limits.validate(self.page_size)?;
        self.metrics
            .tail_reclaim_attempts
            .fetch_add(1, Ordering::Relaxed);
        let mut report = TailReclaimReport::default();
        let mut meta = self.meta.lock();
        validate_free_list_metadata(&meta)?;
        let page_count = meta.page_count;
        if page_count <= 1 {
            return Ok(report);
        }

        // Find the physical free suffix directly. This also reclaims Free pages
        // leaked by a crash before their free-list superblock publication.
        let mut new_page_count = page_count;
        loop {
            if new_page_count <= 1 {
                break;
            }
            if !report.can_charge(1, self.page_size, limits) {
                report.deferred = true;
                self.metrics
                    .tail_reclaim_deferrals
                    .fetch_add(1, Ordering::Relaxed);
                return Ok(report);
            }
            let header = self.read_header(new_page_count - 1)?;
            report.charge(1, self.page_size);
            if header.page_type != PageType::Free {
                break;
            }
            report.tail_pages_scanned += 1;
            new_page_count -= 1;
        }
        if new_page_count == page_count {
            return Ok(report);
        }

        // Validate and remember the existing chain once. Memory is bounded by
        // the visit envelope; there is no second membership tree or survivor
        // vector proportional to the complete free list.
        let free_pages = meta.free_page_count;
        if !report.can_charge(free_pages, self.page_size, limits) {
            report.deferred = true;
            self.metrics
                .tail_reclaim_deferrals
                .fetch_add(1, Ordering::Relaxed);
            return Ok(report);
        }
        let capacity = usize::try_from(free_pages).map_err(|_| {
            free_list_corruption(
                &meta,
                "free-page count exceeds this platform's address space",
            )
        })?;
        let mut chain: Vec<(PageId, PageId)> = Vec::new();
        chain
            .try_reserve_exact(capacity)
            .map_err(|_| PageError::InvalidMaintenanceLimits {
                reason: "bounded tail-reclamation metadata allocation failed".to_string(),
            })?;
        let mut cursor = meta.free_list_head;
        while cursor != 0 {
            if chain.len() as u64 >= free_pages {
                return Err(free_list_corruption(
                    &meta,
                    "free-list traversal exceeds its advertised count",
                ));
            }
            let header = self.read_header(cursor)?;
            report.charge(1, self.page_size);
            report.free_list_pages_scanned += 1;
            if header.page_type != PageType::Free {
                return Err(PageError::UnexpectedPageType {
                    page_id: cursor,
                    found: header.page_type as u8,
                    expected: PageType::Free as u8,
                });
            }
            if header.next_page != 0 && header.next_page >= page_count {
                return Err(free_list_corruption(
                    &meta,
                    format!(
                        "free page {cursor} links beyond the logical file to {}",
                        header.next_page
                    ),
                ));
            }
            chain.push((cursor, header.next_page));
            cursor = header.next_page;
        }
        if chain.len() as u64 != free_pages {
            return Err(free_list_corruption(
                &meta,
                format!(
                    "free-list traversal found {} pages, expected {free_pages}",
                    chain.len()
                ),
            ));
        }

        let mut new_head = 0;
        let mut survivor_count = 0_u64;
        let mut changed_links = 0_u64;
        for (page_id, old_next) in chain.iter().rev() {
            if *page_id < new_page_count {
                if *old_next != new_head {
                    changed_links += 1;
                }
                survivor_count += 1;
                new_head = *page_id;
            }
        }
        // Each changed link needs one page read and one page write. Two
        // superblock publications detach the old list and publish the new one.
        let mutation_visits = changed_links
            .checked_mul(2)
            .and_then(|visits| visits.checked_add(2))
            .ok_or_else(|| PageError::InvalidMaintenanceLimits {
                reason: "tail-reclamation I/O accounting overflowed".to_string(),
            })?;
        if !report.can_charge(mutation_visits, self.page_size, limits) {
            report.deferred = true;
            self.metrics
                .tail_reclaim_deferrals
                .fetch_add(1, Ordering::Relaxed);
            return Ok(report);
        }

        // Detach before rewriting intrusive links. A crash below leaves a
        // valid empty list and leaked pages rather than inconsistent metadata.
        meta.free_list_head = 0;
        meta.free_page_count = 0;
        meta.generation += 1;
        self.write_superblock_meta(&meta)?;
        report.charge(1, self.page_size);
        self.sync()?;

        let mut desired_next = 0;
        for (page_id, old_next) in chain.iter().rev() {
            if *page_id >= new_page_count {
                continue;
            }
            if *old_next != desired_next {
                let mut page = vec![0u8; self.page_size as usize];
                self.read_page_unchecked(*page_id, &mut page)?;
                report.charge(1, self.page_size);
                let mut header = PageHeader::decode(&page, &self.path)?;
                let generation = header.generation.wrapping_add(1);
                header.next_page = desired_next;
                header.encode(&mut page);
                self.write_page_raw(*page_id, &mut page, generation)?;
                report.charge(1, self.page_size);
                report.survivor_links_rewritten += 1;
            }
            desired_next = *page_id;
        }
        self.sync_data_observed()?;
        debug_assert_eq!(desired_next, new_head);
        meta.free_list_head = new_head;
        meta.free_page_count = survivor_count;
        meta.page_count = new_page_count;
        meta.generation += 1;
        self.write_superblock_meta(&meta)?;
        report.charge(1, self.page_size);
        self.sync()?;
        self.truncate_layout_to(new_page_count)?;
        report.pages_truncated = page_count - new_page_count;
        self.metrics
            .tail_reclaim_pages_truncated
            .fetch_add(report.pages_truncated, Ordering::Relaxed);
        Ok(report)
    }

    /// Shrink the physical layout to exactly `page_count` pages: monolithic
    /// `set_len`, or — segmented — shrink the last surviving segment and
    /// DELETE every trailing segment file (the whole point of extents: space
    /// comes back to the filesystem one file at a time).
    fn truncate_layout_to(&self, page_count: u64) -> Result<()> {
        let extent_pages = self.extent_pages();
        if extent_pages == 0 {
            let bytes = page_count
                .checked_mul(u64::from(self.page_size))
                .ok_or(PageError::InvalidPageSize(self.page_size))?;
            let segments = self.segments.read();
            return segments[0]
                .set_len(bytes)
                .map_err(|e| PageError::io(&self.path, e));
        }
        let last_segment = ((page_count.max(1) - 1) / extent_pages) as usize;
        let mut segments = self.segments.write();
        while segments.len() > last_segment + 1 {
            let index = segments.len() - 1;
            segments.pop();
            let path = self.segment_path(index);
            std::fs::remove_file(&path).map_err(|e| PageError::io(&path, e))?;
        }
        let tail_bytes =
            (page_count - last_segment as u64 * extent_pages) * u64::from(self.page_size);
        segments[last_segment]
            .set_len(tail_bytes)
            .map_err(|e| PageError::io(self.segment_path(last_segment), e))?;
        Ok(())
    }

    /// Start migrating a live MONOLITHIC store to `extent_bytes` segments.
    /// Publishing the migration flips the superblock to the segmented (v2)
    /// magic immediately, so an engine that predates segmentation fails
    /// closed rather than reading stale monolithic offsets for pages that
    /// have already moved. Idempotent for the same target; refused when the
    /// store is already segmented or migrating to a different size.
    pub fn begin_extent_migration(&self, extent_bytes: u64) -> Result<()> {
        validate_extent_bytes(extent_bytes, self.page_size)?;
        if extent_bytes == 0 {
            return Err(PageError::InvalidExtentBytes {
                extent_bytes,
                page_size: self.page_size,
            });
        }
        if self.extent_pages() > 0 {
            return Err(PageError::InvalidMaintenanceLimits {
                reason: "store is already extent-segmented".to_string(),
            });
        }
        let target = extent_bytes / u64::from(self.page_size);
        let current = self.migration_target_pages.load(Ordering::Acquire);
        if current == target {
            return Ok(());
        }
        if current != 0 {
            return Err(PageError::InvalidMaintenanceLimits {
                reason: format!(
                    "an extent migration to {current} pages per segment is already in progress"
                ),
            });
        }
        let meta = self.meta.lock();
        self.migration_target_pages.store(target, Ordering::Release);
        // The first extent's pages have identical offsets in both layouts:
        // the migration starts "already done" through the end of extent 0.
        self.migration_watermark.store(target, Ordering::Release);
        self.write_superblock_meta(&meta)?;
        drop(meta);
        self.sync_data_observed()?;
        Ok(())
    }

    /// Copy up to `max_pages` un-migrated pages into their segment files and
    /// durably advance the watermark; flips the store to the segmented
    /// layout when everything has moved. Writers keep running — only writes
    /// into the batch being copied wait, for the batch's duration. Call
    /// repeatedly (a maintenance loop) until `complete`.
    pub fn advance_extent_migration(&self, max_pages: u64) -> Result<ExtentMigrationReport> {
        let target = self.migration_target_pages.load(Ordering::Acquire);
        if target == 0 {
            return Err(PageError::InvalidMaintenanceLimits {
                reason: "no extent migration is in progress".to_string(),
            });
        }
        let max_pages = max_pages.max(1);
        let watermark = self.migration_watermark.load(Ordering::Acquire);
        let page_count = self.meta.lock().page_count;

        if watermark >= page_count {
            // Nothing left below the current allocation horizon: try to
            // complete. Meta is held so no allocation can extend the store
            // between the check and the flip.
            let meta = self.meta.lock();
            if meta.page_count > self.migration_watermark.load(Ordering::Acquire) {
                // An allocation raced in; copy it on the next call.
                drop(meta);
                return Ok(ExtentMigrationReport {
                    pages_copied: 0,
                    watermark: self.migration_watermark.load(Ordering::Acquire),
                    complete: false,
                });
            }
            self.extent_pages.store(target, Ordering::Release);
            self.migration_target_pages.store(0, Ordering::Release);
            self.migration_watermark.store(0, Ordering::Release);
            self.write_superblock_meta(&meta)?;
            drop(meta);
            self.sync_data_observed()?;
            // The monolithic tail of segment 0 is dead — every page beyond
            // the first extent now lives in its segment file.
            let segments = self.segments.read();
            segments[0]
                .set_len(target * u64::from(self.page_size))
                .map_err(|e| PageError::io(&self.path, e))?;
            drop(segments);
            return Ok(ExtentMigrationReport {
                pages_copied: 0,
                watermark: 0,
                complete: true,
            });
        }

        let end = page_count.min(watermark.saturating_add(max_pages));
        let gate = self.migration_gate.lock();
        let mut copied = 0u64;
        let mut cursor = watermark;
        let mut buffer =
            vec![0u8; (8 * 1024 * 1024 / self.page_size as usize).max(1) * self.page_size as usize];
        while cursor < end {
            // One I/O never crosses a target-segment boundary.
            let run = (end - cursor)
                .min((buffer.len() / self.page_size as usize) as u64)
                .min(target - cursor % target);
            let bytes = (run * u64::from(self.page_size)) as usize;
            {
                let segments = self.segments.read();
                let got = crate::pio::read_at(
                    &segments[0],
                    &mut buffer[..bytes],
                    page::file_offset(cursor, self.page_size),
                )
                .map_err(|e| PageError::io(&self.path, e))?;
                if got != bytes {
                    return Err(PageError::ShortRead {
                        page_id: cursor,
                        got,
                        want: bytes,
                    });
                }
            }
            let segment = (cursor / target) as usize;
            self.ensure_segment(segment)?;
            {
                let segments = self.segments.read();
                let written = crate::pio::write_at(
                    &segments[segment],
                    &buffer[..bytes],
                    (cursor % target) * u64::from(self.page_size),
                )
                .map_err(|e| PageError::io(self.segment_path(segment), e))?;
                validate_write_completion(cursor, bytes, written)?;
                if self.fsync {
                    segments[segment]
                        .sync_data()
                        .map_err(|e| PageError::io(self.segment_path(segment), e))?;
                }
            }
            cursor += run;
            copied += run;
        }
        // Copies durable → the atomic watermark makes them authoritative for
        // every reader/writer from this instant. Durability of the watermark
        // itself rides the next superblock write (below, and every later
        // one); a crash in between replays the WAL against the OLD durable
        // watermark, which routes exactly like before the batch — the copies
        // are simply redone.
        self.migration_watermark.store(cursor, Ordering::Release);
        drop(gate);
        self.write_superblock()?;
        self.sync()?;
        Ok(ExtentMigrationReport {
            pages_copied: copied,
            watermark: cursor,
            complete: false,
        })
    }

    /// Read a page into `buffer`, verifying checksum and torn-write trailer.
    pub fn read_page(&self, page_id: PageId, buffer: &mut [u8]) -> Result<PageHeader> {
        debug_assert_eq!(buffer.len(), self.page_size as usize);
        let page_count = self.meta.lock().page_count;
        if page_id >= page_count {
            return Err(PageError::OutOfBounds {
                page_id,
                page_count,
            });
        }
        self.read_page_unchecked(page_id, buffer)
    }

    /// Read without the page-count bound check — used for the superblock during
    /// open, before the page count is known.
    fn read_page_unchecked(&self, page_id: PageId, buffer: &mut [u8]) -> Result<PageHeader> {
        let (segment, offset) = self.locate(page_id);
        let started = Instant::now();
        let got = {
            let segments = self.segments.read();
            let Some(file) = segments.get(segment) else {
                return Err(PageError::ShortRead {
                    page_id,
                    got: 0,
                    want: buffer.len(),
                });
            };
            crate::pio::read_at(file, buffer, offset)
                .map_err(|e| PageError::io(self.segment_path(segment), e))?
        };
        let elapsed = started.elapsed();

        if got != buffer.len() {
            self.metrics.record_read(None, got as u64, elapsed);
            self.metrics.short_reads.fetch_add(1, Ordering::Relaxed);
            return Err(PageError::ShortRead {
                page_id,
                got,
                want: buffer.len(),
            });
        }

        if let Err(error) = page::verify(buffer, page_id) {
            self.metrics.record_read(None, got as u64, elapsed);
            match &error {
                PageError::ChecksumMismatch { .. } => {
                    self.metrics
                        .checksum_failures
                        .fetch_add(1, Ordering::Relaxed);
                }
                PageError::TornPage { .. } => {
                    self.metrics.torn_pages.fetch_add(1, Ordering::Relaxed);
                }
                _ => {}
            }
            return Err(error);
        }

        match PageHeader::decode(buffer, &self.path) {
            Ok(header) => {
                self.metrics
                    .record_read(Some(header.page_type), got as u64, elapsed);
                Ok(header)
            }
            Err(error) => {
                self.metrics.record_read(None, got as u64, elapsed);
                Err(error)
            }
        }
    }

    /// Read only a page's header. Still reads a whole page from the OS — the
    /// point is avoiding a caller-side buffer, not avoiding I/O.
    pub fn read_header(&self, page_id: PageId) -> Result<PageHeader> {
        let mut buffer = vec![0u8; self.page_size as usize];
        self.read_page_unchecked(page_id, &mut buffer)
    }

    /// Write a page, stamping generation and checksum first.
    ///
    /// `buffer` is mutated in place (header generation, trailer, checksum) so
    /// callers cannot forget to finalize, which would produce a page that reads
    /// back as corrupt.
    pub fn write_page(&self, page_id: PageId, buffer: &mut [u8]) -> Result<()> {
        debug_assert_eq!(buffer.len(), self.page_size as usize);
        let generation = {
            let mut meta = self.meta.lock();
            meta.generation += 1;
            meta.generation
        };
        self.write_page_raw(page_id, buffer, generation)
    }

    fn write_page_raw(&self, page_id: PageId, buffer: &mut [u8], generation: u64) -> Result<()> {
        page::finalize(buffer, generation);
        let page_type = PageType::from_u8(buffer[6]);
        // Online migration: a write beyond the first extent must serialize
        // with the batch copier, or a page could be modified between "the
        // copier read it" and "the watermark made the copy authoritative"
        // and the write would vanish. Location is resolved UNDER the gate so
        // a writer released after a publish routes to the new location.
        let migration_target = self.migration_target_pages.load(Ordering::Acquire);
        let _migration_guard = if migration_target > 0 && page_id >= migration_target {
            Some(self.migration_gate.lock())
        } else {
            None
        };
        let (segment, offset) = self.locate(page_id);
        self.ensure_segment(segment)?;
        let to_write = self.faults.intercept(buffer.len())?;
        let started = Instant::now();
        let written = {
            let segments = self.segments.read();
            crate::pio::write_at(&segments[segment], &buffer[..to_write], offset)
                .map_err(|e| PageError::io(self.segment_path(segment), e))?
        };
        self.metrics
            .record_write(page_type, written as u64, started.elapsed());
        validate_write_completion(page_id, to_write, written)?;
        self.mark_segment_dirty(segment);
        Ok(())
    }

    pub fn sync(&self) -> Result<()> {
        if !self.fsync {
            return Ok(());
        }
        self.sync_data_observed()
    }

    fn sync_data_observed(&self) -> Result<()> {
        let started = Instant::now();
        let mut dirty = self.dirty_segments.lock();
        let segments = self.segments.read();
        for index in dirty.iter().copied() {
            let file = segments.get(index).ok_or_else(|| {
                let path = self.segment_path(index);
                PageError::io(
                    &path,
                    io::Error::new(io::ErrorKind::NotFound, "dirty page segment is not open"),
                )
            })?;
            file.sync_data()
                .map_err(|e| PageError::io(self.segment_path(index), e))?;
            self.metrics.segments_synced.fetch_add(1, Ordering::Relaxed);
        }
        drop(segments);
        dirty.clear();
        self.metrics.record_sync(started.elapsed());
        Ok(())
    }

    /// Flush the superblock and fsync. Call at checkpoint.
    pub fn flush(&self) -> Result<()> {
        self.write_superblock()?;
        self.sync()
    }

    /// Read just enough of page 0 to learn the file's real page size, and
    /// report a mismatch against `expected` in terms an operator can act on.
    fn probe_page_size(&self, expected: u32) -> Result<()> {
        const PROBE_BYTES: usize = MIN_PAGE_SIZE as usize;
        let mut probe = [0u8; PROBE_BYTES];
        let got = {
            let segments = self.segments.read();
            crate::pio::read_at(&segments[0], &mut probe, 0)
                .map_err(|e| PageError::io(&self.path, e))?
        };
        if got < PAGE_HEADER_BYTES + 12 {
            // Too small to be any page file at all.
            return Err(PageError::ShortRead {
                page_id: SUPERBLOCK_PAGE_ID,
                got,
                want: PAGE_HEADER_BYTES + 12,
            });
        }
        if probe[0..4] != crate::page::PAGE_MAGIC {
            let mut found = [0u8; 4];
            found.copy_from_slice(&probe[0..4]);
            return Err(PageError::NotAPageFile {
                path: self.path.clone(),
                found,
            });
        }
        let body = &probe[PAGE_HEADER_BYTES..];
        if body[0..8] != SUPERBLOCK_MAGIC && body[0..8] != SUPERBLOCK_MAGIC_SEGMENTED {
            let mut found = [0u8; 4];
            found.copy_from_slice(&body[0..4]);
            return Err(PageError::NotAPageFile {
                path: self.path.clone(),
                found,
            });
        }
        let actual = u32::from_le_bytes(body[8..12].try_into().unwrap());
        if actual != expected {
            return Err(PageError::PageSizeMismatch {
                path: self.path.clone(),
                found: actual,
                expected,
            });
        }
        Ok(())
    }

    fn write_superblock(&self) -> Result<()> {
        let meta = *self.meta.lock();
        self.write_superblock_meta(&meta)
    }

    /// Write an already-locked metadata image. Tail reclamation holds the
    /// metadata mutex across its detach/rewrite/publish sequence, so calling
    /// `write_superblock` there would recursively lock the mutex.
    fn write_superblock_meta(&self, meta: &Superblock) -> Result<()> {
        let mut page = vec![0u8; self.page_size as usize];
        PageHeader::new(SUPERBLOCK_PAGE_ID, PageType::Superblock, self.page_size).encode(&mut page);

        let body = &mut page[PAGE_HEADER_BYTES..];
        let extent_pages = self.extent_pages();
        let migration_target = self.migration_target_pages.load(Ordering::Acquire);
        // The v2 magic gates every state a pre-segmentation engine would
        // misread — including a migration in progress, where some pages
        // already live in segment files a v1 reader knows nothing about.
        if extent_pages == 0 && migration_target == 0 {
            body[0..8].copy_from_slice(&SUPERBLOCK_MAGIC);
        } else {
            body[0..8].copy_from_slice(&SUPERBLOCK_MAGIC_SEGMENTED);
        }
        body[8..12].copy_from_slice(&self.page_size.to_le_bytes());
        body[12..20].copy_from_slice(&meta.page_count.to_le_bytes());
        body[20..28].copy_from_slice(&meta.free_list_head.to_le_bytes());
        body[28..36].copy_from_slice(&meta.free_page_count.to_le_bytes());
        body[36..44].copy_from_slice(&meta.root_page.to_le_bytes());
        body[44..52].copy_from_slice(&meta.checkpoint_lsn.to_le_bytes());
        body[52..60].copy_from_slice(&extent_pages.to_le_bytes());
        body[60..68].copy_from_slice(&migration_target.to_le_bytes());
        body[68..76].copy_from_slice(
            &self
                .migration_watermark
                .load(Ordering::Acquire)
                .to_le_bytes(),
        );

        self.write_page_raw(SUPERBLOCK_PAGE_ID, &mut page, meta.generation.max(1))
    }

    fn read_superblock(&self, expected_page_size: u32) -> Result<Superblock> {
        // Probe the page size before attempting a full-page read.
        //
        // Without this, opening a 4 KiB file with an 8 KiB option reads past the
        // end of a one-page file and reports `ShortRead` — technically a refusal,
        // but it tells the operator nothing about what to fix. The probe only
        // needs the header plus the superblock body, both well inside the
        // smallest legal page, and its findings are advisory: the authoritative
        // checksum and trailer verification still happens on the full read below.
        self.probe_page_size(expected_page_size)?;

        let mut page = vec![0u8; expected_page_size as usize];
        let header = self.read_page_unchecked(SUPERBLOCK_PAGE_ID, &mut page)?;
        if header.page_type != PageType::Superblock {
            return Err(PageError::UnexpectedPageType {
                page_id: SUPERBLOCK_PAGE_ID,
                found: header.page_type as u8,
                expected: PageType::Superblock as u8,
            });
        }

        let body = &page[PAGE_HEADER_BYTES..];
        let segmented = body[0..8] == SUPERBLOCK_MAGIC_SEGMENTED;
        if !segmented && body[0..8] != SUPERBLOCK_MAGIC {
            let mut found = [0u8; 4];
            found.copy_from_slice(&body[0..4]);
            return Err(PageError::NotAPageFile {
                path: self.path.clone(),
                found,
            });
        }
        let page_size = u32::from_le_bytes(body[8..12].try_into().unwrap());
        if page_size != expected_page_size {
            return Err(PageError::PageSizeMismatch {
                path: self.path.clone(),
                found: page_size,
                expected: expected_page_size,
            });
        }
        let (extent_pages, migration_target_pages, migration_watermark) = if segmented {
            (
                u64::from_le_bytes(body[52..60].try_into().unwrap()),
                u64::from_le_bytes(body[60..68].try_into().unwrap()),
                u64::from_le_bytes(body[68..76].try_into().unwrap()),
            )
        } else {
            // Legacy superblocks carry zeroes here; treat as monolithic
            // regardless.
            (0, 0, 0)
        };

        Ok(Superblock {
            page_count: u64::from_le_bytes(body[12..20].try_into().unwrap()),
            free_list_head: u64::from_le_bytes(body[20..28].try_into().unwrap()),
            free_page_count: u64::from_le_bytes(body[28..36].try_into().unwrap()),
            generation: header.generation,
            root_page: u64::from_le_bytes(body[36..44].try_into().unwrap()),
            checkpoint_lsn: u64::from_le_bytes(body[44..52].try_into().unwrap()),
            extent_pages,
            migration_target_pages,
            migration_watermark,
        })
    }
}

/// Offline page-file relayout: rewrite a store between the monolithic and
/// extent-segmented layouts (or between extent sizes) without touching the
/// WAL — WAL records address page ids, which are layout-independent, so a
/// pending log replays correctly against the new layout on the next open.
///
/// The caller must guarantee exclusive access (the CLI holds the store's
/// directory lock). Crash safety is rename-based:
///
/// 1. the complete target layout is built under `<base>.relayout/`;
/// 2. every source file is renamed to `<name>.pre-relayout`;
/// 3. target files are renamed into place;
/// 4. `.pre-relayout` files and the staging directory are removed.
///
/// [`repair_interrupted_relayout`] (run first, always) rolls back any state
/// left by a crash between those steps: as long as one `.pre-relayout` file
/// exists the source is authoritative and is restored; a staging directory
/// without renames is simply deleted.
pub fn convert_extent_layout(
    base: &Path,
    page_size: u32,
    target_extent_bytes: u64,
    fsync: bool,
) -> Result<()> {
    validate_extent_bytes(target_extent_bytes, page_size)?;
    repair_interrupted_relayout(base)?;
    let source = PageStore::open(
        base,
        PageStoreOptions {
            page_size,
            fsync: false,
            create: false,
            extent_bytes: 0,
        },
    )?;
    let target_extent_pages = target_extent_bytes / u64::from(page_size);
    if source.extent_pages() == target_extent_pages {
        return Ok(());
    }
    let meta = *source.meta.lock();
    let staging = relayout_staging_dir(base);
    let _ = std::fs::remove_dir_all(&staging);
    std::fs::create_dir_all(&staging).map_err(|e| PageError::io(&staging, e))?;

    let file_name = |index: usize| -> PathBuf {
        staging.join(
            segment_path_for(base, index)
                .file_name()
                .expect("segment paths have file names")
                .to_os_string(),
        )
    };
    let target = PageStore {
        path: file_name(0),
        segments: parking_lot::RwLock::new(Vec::new()),
        dirty_segments: Mutex::new(BTreeSet::new()),
        extent_pages: AtomicU64::new(target_extent_pages),
        migration_target_pages: AtomicU64::new(0),
        migration_watermark: AtomicU64::new(0),
        migration_gate: Mutex::new(()),
        page_size,
        fsync,
        meta: Mutex::new(meta),
        metrics: PageIoMetrics::default(),
        faults: FaultInjection::default(),
    };
    target.ensure_segment(0)?;
    // Raw byte copy, page-aligned batches: free pages and all. Content is
    // moved verbatim; only the superblock is rewritten for the new layout.
    let batch_pages = (8 * 1024 * 1024 / page_size as usize).max(1) as u64;
    let mut buffer = vec![0u8; (batch_pages * u64::from(page_size)) as usize];
    let mut page_id = 0u64;
    while page_id < meta.page_count {
        // Never cross a segment boundary of either layout in one I/O.
        let boundary = |extent_pages: u64| match extent_pages {
            0 => u64::MAX,
            pages => pages - page_id % pages,
        };
        let run = batch_pages
            .min(meta.page_count - page_id)
            .min(boundary(source.extent_pages()))
            .min(boundary(target_extent_pages));
        let bytes = (run * u64::from(page_size)) as usize;
        {
            let (segment, offset) = source.locate(page_id);
            let segments = source.segments.read();
            let got = crate::pio::read_at(&segments[segment], &mut buffer[..bytes], offset)
                .map_err(|e| PageError::io(source.segment_path(segment), e))?;
            if got != bytes {
                return Err(PageError::ShortRead {
                    page_id,
                    got,
                    want: bytes,
                });
            }
        }
        let target_segment = {
            let (segment, offset) = target.locate(page_id);
            target.ensure_segment(segment)?;
            let segments = target.segments.read();
            let written = crate::pio::write_at(&segments[segment], &buffer[..bytes], offset)
                .map_err(|e| PageError::io(target.segment_path(segment), e))?;
            validate_write_completion(page_id, bytes, written)?;
            segment
        };
        target.mark_segment_dirty(target_segment);
        page_id += run;
    }
    // Rewrite page 0 for the target layout (magic + extent size + checksum).
    target.write_superblock()?;
    if fsync {
        target.sync_data_observed()?;
    }
    let target_count = target.segments.read().len();
    drop(target);
    let source_paths = source.segment_paths();
    drop(source);

    // Swap. Renaming the source away FIRST means any crash from here on
    // leaves `.pre-relayout` files, which repair treats as "source wins".
    for (index, path) in source_paths.iter().enumerate() {
        let parked = pre_relayout_path(base, index);
        std::fs::rename(path, &parked).map_err(|e| PageError::io(&parked, e))?;
    }
    for index in 0..target_count {
        let from = file_name(index);
        let to = segment_path_for(base, index);
        std::fs::rename(&from, &to).map_err(|e| PageError::io(&to, e))?;
    }
    if fsync {
        if let Some(parent) = base.parent() {
            if let Ok(dir) = File::open(parent) {
                let _ = dir.sync_all();
            }
        }
    }
    for (index, _) in source_paths.iter().enumerate() {
        let parked = pre_relayout_path(base, index);
        std::fs::remove_file(&parked).map_err(|e| PageError::io(&parked, e))?;
    }
    let _ = std::fs::remove_dir_all(&staging);
    Ok(())
}

/// Roll back a relayout interrupted between its rename steps. Source files
/// (`.pre-relayout`) are authoritative: any final-name file that also has a
/// parked twin is a partially-swapped target and is deleted before the park
/// is renamed back. A staging directory with no parked files means the swap
/// never started; it is deleted.
pub fn repair_interrupted_relayout(base: &Path) -> Result<()> {
    let mut index = 0usize;
    let mut restored = false;
    loop {
        let parked = pre_relayout_path(base, index);
        if !parked.exists() {
            break;
        }
        let live = segment_path_for(base, index);
        if live.exists() {
            std::fs::remove_file(&live).map_err(|e| PageError::io(&live, e))?;
        }
        std::fs::rename(&parked, &live).map_err(|e| PageError::io(&live, e))?;
        restored = true;
        index += 1;
    }
    if restored {
        // Final-name segments past the restored source's segment count can
        // only be leftovers of a longer target layout.
        let mut extra = index;
        loop {
            let live = segment_path_for(base, extra);
            if !live.exists() {
                break;
            }
            std::fs::remove_file(&live).map_err(|e| PageError::io(&live, e))?;
            extra += 1;
        }
    }
    let _ = std::fs::remove_dir_all(relayout_staging_dir(base));
    Ok(())
}

fn relayout_staging_dir(base: &Path) -> PathBuf {
    let mut os = base.as_os_str().to_os_string();
    os.push(".relayout");
    PathBuf::from(os)
}

fn pre_relayout_path(base: &Path, index: usize) -> PathBuf {
    let mut os = segment_path_for(base, index).into_os_string();
    os.push(".pre-relayout");
    PathBuf::from(os)
}

/// Segment file naming: the base path itself for segment 0, `<base>.<n>`
/// above it (`store.pages`, `store.pages.1`, `store.pages.2`, …).
pub(crate) fn segment_path_for(base: &Path, index: usize) -> PathBuf {
    if index == 0 {
        base.to_path_buf()
    } else {
        let mut os = base.as_os_str().to_os_string();
        os.push(format!(".{index}"));
        PathBuf::from(os)
    }
}

fn validate_extent_bytes(extent_bytes: u64, page_size: u32) -> Result<()> {
    if extent_bytes == 0 {
        return Ok(());
    }
    if extent_bytes < MIN_EXTENT_BYTES || extent_bytes % u64::from(page_size) != 0 {
        return Err(PageError::InvalidExtentBytes {
            extent_bytes,
            page_size,
        });
    }
    Ok(())
}

fn validate_write_completion(page_id: PageId, requested: usize, written: usize) -> Result<()> {
    if written == requested {
        Ok(())
    } else {
        Err(PageError::ShortWrite {
            page_id,
            got: written,
            want: requested,
        })
    }
}

