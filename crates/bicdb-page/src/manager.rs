    #[test]
    fn metrics_count_and_classify_the_io_that_actually_happened() {
        let dir = TempDir::new().unwrap();
        let store = store(&dir);
        let before = store.metrics.snapshot();

        let typed_pages = [
            PageType::Heap,
            PageType::Overflow,
            PageType::BTreeInterior,
            PageType::BTreeLeaf,
        ]
        .map(|page_type| (page_type, store.allocate(page_type).unwrap()));
        for (_, page_id) in typed_pages {
            store.read_header(page_id).unwrap();
        }
        let free_page = store.allocate(PageType::Heap).unwrap();
        store.free(free_page).unwrap();
        assert_eq!(
            store.read_header(free_page).unwrap().page_type,
            PageType::Free
        );
        assert_eq!(
            store.read_header(SUPERBLOCK_PAGE_ID).unwrap().page_type,
            PageType::Superblock
        );

        let after = store.metrics.snapshot();
        assert!(after.writes > before.writes);
        assert!(after.reads > before.reads);
        assert_eq!(after.allocations, before.allocations + 5);
        assert!(after.bytes_written >= u64::from(store.page_size()));
        assert!(after.bytes_read >= u64::from(store.page_size()));
        assert!(after.page_types.superblock.reads > 0);
        assert!(after.page_types.superblock.writes > 0);
        assert!(after.page_types.heap.reads > 0);
        assert!(after.page_types.heap.writes > 0);
        assert!(after.page_types.overflow.reads > 0);
        assert!(after.page_types.overflow.writes > 0);
        assert!(after.page_types.btree_interior.reads > 0);
        assert!(after.page_types.btree_interior.writes > 0);
        assert!(after.page_types.btree_leaf.reads > 0);
        assert!(after.page_types.btree_leaf.writes > 0);
        assert!(after.page_types.free.reads > 0);
        assert!(after.page_types.free.writes > 0);
        assert_eq!(
            after.page_types.unclassified,
            PageClassIoSnapshot::default()
        );

        let classified = after.page_types.total();
        assert_eq!(classified.reads, after.reads);
        assert_eq!(classified.writes, after.writes);
        assert_eq!(classified.bytes_read, after.bytes_read);
        assert_eq!(classified.bytes_written, after.bytes_written);
        assert_eq!(after.read_latency.count, after.reads);
        assert_eq!(after.write_latency.count, after.writes);
        assert_eq!(after.read_latency.cumulative_buckets[8], after.reads);
        assert_eq!(after.write_latency.cumulative_buckets[8], after.writes);
        assert!(after.is_consistent());
    }

