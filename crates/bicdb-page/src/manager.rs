    #[test]
    fn reachable_free_list_truncates_at_the_first_corrupt_link() {
        let dir = TempDir::new().unwrap();
        let path = dir.path().join("test.pages");
        let store = PageStore::open(&path, PageStoreOptions::default().with_fsync(false)).unwrap();
        let a = store.allocate(PageType::Heap).unwrap();
        let b = store.allocate(PageType::Heap).unwrap();
        let c = store.allocate(PageType::Heap).unwrap();
        store.free(a).unwrap();
        store.free(b).unwrap();
        store.free(c).unwrap();
        assert_eq!(store.free_list_head(), c);
        assert_eq!(store.free_page_count(), 3);

        // Re-type the MIDDLE link behind the list's back — the observed
        // post-crash state: the list is reachable but walks into a page that
        // is no longer Free. Every allocation now fails closed.
        let mut page = vec![0u8; store.page_size as usize];
        PageHeader::new(b, PageType::Overflow, store.page_size).encode(&mut page);
        store.write_page_raw(b, &mut page, 1).unwrap();
        assert!(matches!(
            store.allocate(PageType::Heap).unwrap_err(),
            PageError::UnexpectedPageType { page_id, .. } if page_id == b
        ));

        // Dry run reports without touching anything.
        let report = store.truncate_free_list_at_corruption(false).unwrap();
        assert_eq!(
            (
                report.advertised,
                report.valid_prefix,
                report.corrupt_page,
                report.applied
            ),
            (3, 1, Some(b), false)
        );
        assert_eq!(store.free_page_count(), 3);
        assert!(store.allocate(PageType::Heap).is_err());

        // Apply keeps the valid prefix (just `c`) and abandons b and a.
        let report = store.truncate_free_list_at_corruption(true).unwrap();
        assert!(report.applied);
        assert_eq!((store.free_list_head(), store.free_page_count()), (c, 1));

        // The published truncation survives reopen, and the healthy list is
        // left alone.
        drop(store);
        let store = PageStore::open(&path, PageStoreOptions::default().with_fsync(false)).unwrap();
        assert_eq!((store.free_list_head(), store.free_page_count()), (c, 1));
        let after = store.truncate_free_list_at_corruption(true).unwrap();
        assert!(
            !after.applied,
            "a healthy list must not be repaired: {after:?}"
        );

        // Allocation serves the surviving free page, then extends the file —
        // the abandoned pages never re-enter circulation.
        assert_eq!(store.allocate(PageType::Heap).unwrap(), c);
        let fresh = store.allocate(PageType::Heap).unwrap();
        assert!(
            fresh != a && fresh != b,
            "an abandoned page re-entered circulation"
        );
    }

