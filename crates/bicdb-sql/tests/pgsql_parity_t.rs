#[test]
fn view_options_are_catalogued_and_alterable() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(&mut session, "CREATE TABLE b (a int, who text);
             INSERT INTO b VALUES (1, 'alice'), (2, 'bob');
             CREATE VIEW v1 WITH (security_barrier) AS SELECT * FROM b;
             CREATE VIEW v2 WITH (security_invoker = false, security_barrier = true) AS SELECT * FROM b;
             CREATE VIEW v3 AS SELECT * FROM b WHERE a > 0 WITH LOCAL CHECK OPTION");
    assert_eq!(
        rows(
            &mut session,
            "SELECT relname, reloptions::text FROM pg_class WHERE relname LIKE 'v_' ORDER BY 1"
        ),
        vec![
            "v1|{security_barrier=true}",
            "v2|{security_invoker=false,security_barrier=true}",
            "v3|{check_option=local}",
        ]
    );
    for (sql, state) in [
        (
            "CREATE VIEW f1 WITH (security_barrier = 100) AS SELECT 1",
            "22023",
        ),
        ("CREATE VIEW f2 WITH (nosuch = 1) AS SELECT 1", "22023"),
        ("ALTER VIEW v1 SET (nosuch = 1)", "22023"),
    ] {
        assert_eq!(sqlstate(&mut session, sql), state, "{sql}");
    }
    exec(
        &mut session,
        "ALTER VIEW v1 SET (security_invoker); ALTER VIEW v1 RESET (security_barrier)",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT reloptions::text FROM pg_class WHERE relname = 'v1'"
        ),
        vec!["{security_invoker=true}"]
    );
    // security_invoker reads as the caller, with the caller's row security.
    exec(
        &mut session,
        "CREATE ROLE alice; CREATE ROLE bob;
             ALTER TABLE b ENABLE ROW LEVEL SECURITY;
             CREATE POLICY own ON b USING (who = current_user);
             GRANT SELECT ON b, v1, v2 TO alice; GRANT SELECT ON v1, v2 TO bob",
    );
    exec(&mut session, "SET ROLE alice");
    assert_eq!(rows(&mut session, "SELECT a FROM v1"), vec!["1"]);
    exec(&mut session, "RESET ROLE; SET ROLE bob");
    // bob has no privilege on b: the invoker view refuses, the owner view reads as its owner.
    assert_eq!(sqlstate(&mut session, "SELECT a FROM v1"), "42501");
    assert_eq!(rows(&mut session, "SELECT count(*) FROM v2"), vec!["2"]);
    assert_eq!(
        sqlstate(&mut session, "ALTER VIEW v2 SET (security_invoker)"),
        "42501"
    );
}

#[test]
fn insert_overriding_system_and_user_value() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE TABLE ia (a int GENERATED ALWAYS AS IDENTITY, b text);
             CREATE TABLE ib (a int GENERATED BY DEFAULT AS IDENTITY, b text);
             CREATE TABLE ig (a int, g int GENERATED ALWAYS AS (a * 2) STORED)",
    );
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO ia VALUES (5, 'x')"),
        "428C9"
    );
    exec(
        &mut session,
        "INSERT INTO ia OVERRIDING SYSTEM VALUE VALUES (5, 'x');
             INSERT INTO ia OVERRIDING USER VALUE VALUES (99, 'y');
             INSERT INTO ib OVERRIDING USER VALUE SELECT 99, 'p' UNION ALL SELECT 98, 'q';
             INSERT INTO ib VALUES (50, 'r')",
    );
    assert_eq!(
        rows(&mut session, "SELECT a, b FROM ia ORDER BY a"),
        vec!["1|y", "5|x"]
    );
    assert_eq!(
        rows(&mut session, "SELECT a, b FROM ib ORDER BY a"),
        vec!["1|p", "2|q", "50|r"]
    );
    // Generated expression columns stay protected.
    assert_eq!(
        sqlstate(
            &mut session,
            "INSERT INTO ig (a, g) OVERRIDING SYSTEM VALUE VALUES (1, 5)"
        ),
        "428C9"
    );
    // The exemption belongs to that one statement.
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO ia VALUES (6, 'z')"),
        "428C9"
    );
    exec(
        &mut session,
        "MERGE INTO ia t USING (SELECT 7 AS a, 'm' AS b) s ON t.a = s.a
             WHEN NOT MATCHED THEN INSERT (a, b) OVERRIDING SYSTEM VALUE VALUES (s.a, s.b)",
    );
    assert_eq!(
        rows(&mut session, "SELECT b FROM ia WHERE a = 7"),
        vec!["m"]
    );
    assert_eq!(
        sqlstate(
            &mut session,
            "MERGE INTO ia t USING (SELECT 8 AS a) s ON t.a = s.a
             WHEN NOT MATCHED THEN INSERT (a, b) VALUES (s.a, 'n')"
        ),
        "428C9"
    );
}

#[test]
fn drop_owned_and_reassign_owned() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(
        &mut session,
        "CREATE ROLE gone; CREATE ROLE heir; CREATE ROLE outsider;
             CREATE TABLE keep (a int); GRANT SELECT ON keep TO gone;
             CREATE TABLE t (a int); ALTER TABLE t OWNER TO gone;
             CREATE VIEW v AS SELECT * FROM t; ALTER VIEW v OWNER TO gone;
             CREATE SEQUENCE q; ALTER SEQUENCE q OWNER TO gone;
             CREATE TABLE t2 (a int); ALTER TABLE t2 OWNER TO heir",
    );
    exec(&mut session, "SET ROLE outsider");
    assert_eq!(sqlstate(&mut session, "DROP OWNED BY gone"), "42501");
    assert_eq!(
        sqlstate(&mut session, "REASSIGN OWNED BY heir TO gone"),
        "42501"
    );
    exec(&mut session, "RESET ROLE");
    exec(&mut session, "REASSIGN OWNED BY heir TO outsider");
    assert_eq!(
        rows(
            &mut session,
            "SELECT tableowner FROM pg_tables WHERE tablename = 't2'"
        ),
        vec!["outsider"]
    );
    exec(&mut session, "DROP OWNED BY gone");
    assert_eq!(
        rows(
            &mut session,
            "SELECT count(*) FROM pg_class WHERE relname IN ('t', 'v', 'q')"
        ),
        vec!["0"]
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT has_table_privilege('gone', 'keep', 'SELECT')"
        ),
        vec!["f"]
    );
    exec(&mut session, "DROP ROLE gone");
    // RESTRICT refuses when an object of another role depends on one.
    exec(
        &mut session,
        "CREATE ROLE r2; CREATE TABLE d (a int); ALTER TABLE d OWNER TO r2;
             CREATE VIEW dv AS SELECT * FROM d",
    );
    assert_eq!(sqlstate(&mut session, "DROP OWNED BY r2"), "2BP01");
    assert_eq!(
        rows(
            &mut session,
            "SELECT count(*) FROM pg_class WHERE relname = 'd'"
        ),
        vec!["1"]
    );
    exec(&mut session, "DROP OWNED BY r2 CASCADE");
    assert_eq!(
        rows(
            &mut session,
            "SELECT count(*) FROM pg_class WHERE relname IN ('d', 'dv')"
        ),
        vec!["0"]
    );
}

#[test]
fn alter_column_identity_forms_and_storage() {
    let root = tempfile::tempdir().unwrap();
    let mut db = open(root.path());
    let mut session = SqlSession::new(&mut db);
    exec(&mut session, "CREATE TABLE i1 (a int NOT NULL, b text);
             ALTER TABLE i1 ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 5);
             INSERT INTO i1 (b) VALUES ('x'), ('y')");
    assert_eq!(
        rows(&mut session, "SELECT a, b FROM i1 ORDER BY a"),
        vec!["10|x", "15|y"]
    );
    for (sql, state) in [
        ("CREATE TABLE i2 (a int); ALTER TABLE i2 ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY", "55000"),
        ("ALTER TABLE i1 ALTER COLUMN a ADD GENERATED BY DEFAULT AS IDENTITY", "55000"),
        ("CREATE TABLE i3 (a int NOT NULL DEFAULT 1); ALTER TABLE i3 ALTER a ADD GENERATED ALWAYS AS IDENTITY", "55000"),
        ("ALTER TABLE i1 ALTER COLUMN b SET INCREMENT BY 2", "55000"),
        ("ALTER TABLE i1 ALTER COLUMN b DROP IDENTITY", "55000"),
        ("CREATE TABLE i4 (a int); ALTER TABLE i4 ALTER a SET STORAGE EXTERNAL", "42804"),
    ] {
        assert_eq!(sqlstate(&mut session, sql), state, "{sql}");
    }
    exec(&mut session, "ALTER TABLE i1 ALTER COLUMN a SET GENERATED BY DEFAULT SET INCREMENT BY 2 RESTART WITH 100;
             INSERT INTO i1 (b) VALUES ('z'); INSERT INTO i1 VALUES (1, 'w')");
    assert_eq!(
        rows(&mut session, "SELECT a, b FROM i1 ORDER BY a"),
        vec!["1|w", "10|x", "15|y", "100|z"]
    );
    exec(
        &mut session,
        "ALTER TABLE i1 ALTER COLUMN a DROP IDENTITY;
             ALTER TABLE i1 ALTER COLUMN a DROP IDENTITY IF EXISTS",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT attidentity, attnotnull FROM pg_attribute WHERE attrelid = 'i1'::regclass AND attname = 'a'"
        ),
        vec!["|t"]
    );
    assert_eq!(
        sqlstate(&mut session, "INSERT INTO i1 (b) VALUES ('v')"),
        "23502"
    );
    exec(
        &mut session,
        "CREATE TABLE st (a text, b text); CREATE TABLE stc () INHERITS (st);
             ALTER TABLE st ALTER COLUMN a SET STORAGE EXTERNAL;
             ALTER TABLE ONLY st ALTER COLUMN b SET STORAGE MAIN",
    );
    assert_eq!(
        rows(
            &mut session,
            "SELECT attrelid::regclass::text, attname, attstorage FROM pg_attribute \
             WHERE attrelid IN ('st'::regclass, 'stc'::regclass) AND attnum > 0 ORDER BY 1, attnum"
        ),
        vec!["st|a|e", "st|b|m", "stc|a|e", "stc|b|x"]
    );
}

