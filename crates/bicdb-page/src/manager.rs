/// One atomic free-list publication is generated by one bounded vacuum step.
/// Keep validation proportional to that already-authorized step, never to the
/// database or complete free list.
pub(crate) const MAX_FREE_LIST_ADOPTION_PAGES: u64 = 65_536;
/// Hard ceiling for page reads and writes performed by one opportunistic
/// checkpoint tail-reclamation attempt.
pub const MAX_TAIL_RECLAIM_PAGE_VISITS: u64 = 8_192;
/// Hard logical I/O ceiling for one opportunistic checkpoint tail-reclamation
/// attempt. Larger rewrites defer to the planned resumable maintenance path.
pub const MAX_TAIL_RECLAIM_IO_BYTES: u64 = 64 * 1024 * 1024;

/// Non-weakenable resource envelope for one checkpoint tail-reclamation pass.
#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TailReclaimLimits {
    pub max_page_visits: u64,
    pub max_io_bytes: u64,
}

impl Default for TailReclaimLimits {
    fn default() -> Self {
        Self {
            max_page_visits: MAX_TAIL_RECLAIM_PAGE_VISITS,
            max_io_bytes: MAX_TAIL_RECLAIM_IO_BYTES,
        }
    }
}

impl TailReclaimLimits {
    pub fn validate(self, page_size: u32) -> Result<()> {
        page::validate_page_size(page_size)?;
        if self.max_page_visits == 0
            || self.max_page_visits > MAX_TAIL_RECLAIM_PAGE_VISITS
            || self.max_io_bytes < u64::from(page_size)
            || self.max_io_bytes > MAX_TAIL_RECLAIM_IO_BYTES
        {
            return Err(PageError::InvalidMaintenanceLimits {
                reason: format!(
                    "tail reclamation requires 1..={MAX_TAIL_RECLAIM_PAGE_VISITS} page visits and {}..={MAX_TAIL_RECLAIM_IO_BYTES} I/O bytes",
                    page_size
                ),
            });
        }
        Ok(())
    }
}

